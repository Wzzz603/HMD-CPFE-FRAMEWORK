def iter_baseline_point_chunks(
    split_name: str,
    cfg=CFG,
    include_first_step: Optional[bool] = None,
    max_points: Optional[int] = None,
) -> Iterator[Dict[str, np.ndarray]]:
    """
    Yield current-step-only samples for Linear/Ridge/Lasso.

    Each yielded dictionary contains:
        x                  [P, 22] float32
        y                  [P, 6]  float32
        weight             [P]     float32
        trajectory_index   [P]     int64
        time_index         [P]     int16

    No sequence history is supplied to the baseline models.

    Parameters
    ----------
    split_name:
        "train" or "val".

    include_first_step:
        For fitting, use cfg.BASELINE_INCLUDE_FIRST_STEP_IN_FIT.
        For LCS-comparable validation metrics, pass False.

    max_points:
        Optional deterministic cap for debugging or optional baseline
        subsampling. Formal comparisons should use None.
    """
    info = inspect_phase_h5(cfg)

    if include_first_step is None:
        include_first_step = bool(
            cfg.BASELINE_INCLUDE_FIRST_STEP_IN_FIT
        )

    if split_name == "train":
        max_trajectories = cfg.MAX_TRAIN_TRAJECTORIES
        configured_point_cap = cfg.BASELINE_MAX_TRAIN_POINTS
    elif split_name == "val":
        max_trajectories = cfg.MAX_VAL_TRAJECTORIES
        configured_point_cap = cfg.BASELINE_MAX_VAL_POINTS
    else:
        raise ValueError("split_name must be train or val")

    if max_points is None:
        max_points = configured_point_cap

    indices = _load_split_indices(
        info=info,
        split_name=split_name,
        max_count=max_trajectories,
        random_seed=cfg.RANDOM_SEED,
    )

    time_start = 0 if include_first_step else 1
    time_indices = np.arange(
        time_start,
        info.sequence_length,
        dtype=np.int16,
    )
    points_per_trajectory = int(time_indices.size)
    if points_per_trajectory <= 0:
        raise ValueError("No time points selected")

    point_chunk_limit = int(cfg.BASELINE_POINT_CHUNK_SIZE)
    trajectories_per_chunk = max(
        1,
        point_chunk_limit // points_per_trajectory,
    )

    store = PhaseH5Store(
        info=info,
        access_mode="h5",
    )

    emitted = 0
    try:
        for start in range(0, indices.size, trajectories_per_chunk):
            end = min(start + trajectories_per_chunk, indices.size)
            source_indices = indices[start:end]
            arrays = store.read_core_rows(source_indices)

            x_sequence = assemble_model_inputs_numpy(
                F_end=arrays["F_end"],
                theta_start=arrays["theta_start"],
                static_values=arrays["static"],
                info=info,
            )
            y_sequence = np.asarray(
                arrays["sigma_end"],
                dtype=np.float32,
            )
            trajectory_weights = extract_sample_weights(
                arrays["static"],
                info,
            )

            x_selected = x_sequence[:, time_start:, :]
            y_selected = y_sequence[:, time_start:, :]

            batch_trajectories = int(source_indices.size)
            point_count = batch_trajectories * points_per_trajectory

            x = np.ascontiguousarray(
                x_selected.reshape(point_count, INPUT_DIM),
                dtype=np.float32,
            )
            y = np.ascontiguousarray(
                y_selected.reshape(point_count, TARGET_DIM),
                dtype=np.float32,
            )
            weight = np.repeat(
                trajectory_weights,
                points_per_trajectory,
            ).astype(np.float32, copy=False)
            trajectory_index = np.repeat(
                source_indices,
                points_per_trajectory,
            ).astype(np.int64, copy=False)
            time_index = np.tile(
                time_indices,
                batch_trajectories,
            ).astype(np.int16, copy=False)

            if max_points is not None:
                remaining = int(max_points) - emitted
                if remaining <= 0:
                    break
                if point_count > remaining:
                    x = x[:remaining]
                    y = y[:remaining]
                    weight = weight[:remaining]
                    trajectory_index = trajectory_index[:remaining]
                    time_index = time_index[:remaining]
                    point_count = remaining

            emitted += point_count

            yield {
                "x": x,
                "y": y,
                "weight": np.ascontiguousarray(weight),
                "trajectory_index": np.ascontiguousarray(
                    trajectory_index
                ),
                "time_index": np.ascontiguousarray(time_index),
            }

            if max_points is not None and emitted >= int(max_points):
                break
    finally:
        store.close()


