def read_trajectory_metadata(
    trajectory_indices: Sequence[int],
    cfg=CFG,
) -> Dict[str, np.ndarray]:
    info = inspect_phase_h5(cfg)
    indices = np.asarray(trajectory_indices, dtype=np.int64)
    store = PhaseH5Store(info=info, access_mode="h5")
    try:
        return store.read_metadata_rows(indices)
    finally:
        store.close()


