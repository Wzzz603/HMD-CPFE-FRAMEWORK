class PhaseH5Store:
    """
    Shared core data store.

    In "ram" mode the four core arrays are loaded exactly once and shared by
    the train and validation Dataset objects in the main process.

    In "h5" mode each process lazily opens its own read-only H5 handle.
    """

    def __init__(
        self,
        info: PhaseH5Info,
        access_mode: str,
    ) -> None:
        access_mode = str(access_mode).lower().strip()
        if access_mode not in ("ram", "h5"):
            raise ValueError("access_mode must be 'ram' or 'h5'")

        self.info = info
        self.access_mode = access_mode

        self._ram_arrays: Optional[Dict[str, np.ndarray]] = None
        self._h5: Optional[h5py.File] = None
        self._h5_pid: Optional[int] = None

        if self.access_mode == "ram":
            self._load_core_arrays_to_ram()

    def _load_core_arrays_to_ram(self) -> None:
        print(
            "[RAM LOAD] Loading core arrays once: %.3f GiB from %s"
            % (self.info.estimated_core_gib, self.info.path)
        )
        with h5py.File(self.info.path, "r") as h5:
            arrays = {
                "F_end": np.asarray(h5["F_end"][:], dtype=np.float32),
                "theta_start": np.asarray(
                    h5["theta_start"][:],
                    dtype=np.float32,
                ),
                "sigma_end": np.asarray(
                    h5["sigma_end"][:],
                    dtype=np.float32,
                ),
                "static": np.asarray(h5["static"][:], dtype=np.float32),
            }

        expected = self.info.trajectory_count
        for name, array in arrays.items():
            if int(array.shape[0]) != expected:
                raise RuntimeError(
                    "RAM array %s has N=%d, expected %d"
                    % (name, array.shape[0], expected)
                )
            if not array.flags.c_contiguous:
                arrays[name] = np.ascontiguousarray(array)

        self._ram_arrays = arrays
        print("[RAM LOAD] Completed")

    def _get_h5(self) -> h5py.File:
        pid = os.getpid()
        if (
            self._h5 is None
            or self._h5_pid != pid
            or not bool(self._h5.id.valid)
        ):
            self.close_h5()
            self._h5 = h5py.File(
                self.info.path,
                "r",
                libver="latest",
                swmr=True,
            )
            self._h5_pid = pid
        return self._h5

    def close_h5(self) -> None:
        if self._h5 is not None:
            try:
                self._h5.close()
            finally:
                self._h5 = None
                self._h5_pid = None

    def close(self) -> None:
        self.close_h5()
        self._ram_arrays = None

    def __del__(self) -> None:
        try:
            self.close_h5()
        except Exception:
            pass

    def __getstate__(self) -> Dict[str, object]:
        state = dict(self.__dict__)
        # H5 handles are process-local and cannot be pickled.
        state["_h5"] = None
        state["_h5_pid"] = None
        return state

    def read_core_rows(
        self,
        source_indices: np.ndarray,
    ) -> Dict[str, np.ndarray]:
        source_indices = np.asarray(source_indices, dtype=np.int64)
        if source_indices.ndim != 1:
            raise ValueError("source_indices must be one-dimensional")
        if source_indices.size == 0:
            raise ValueError("source_indices cannot be empty")

        if np.any(source_indices < 0) or np.any(
            source_indices >= self.info.trajectory_count
        ):
            raise IndexError("source_indices out of range")

        if self.access_mode == "ram":
            assert self._ram_arrays is not None
            return {
                name: np.asarray(array[source_indices])
                for name, array in self._ram_arrays.items()
            }

        h5 = self._get_h5()
        return {
            name: _read_h5_rows(h5[name], source_indices)
            for name in ("F_end", "theta_start", "sigma_end", "static")
        }

    def read_metadata_rows(
        self,
        source_indices: np.ndarray,
    ) -> Dict[str, np.ndarray]:
        source_indices = np.asarray(source_indices, dtype=np.int64)
        if source_indices.ndim != 1 or source_indices.size == 0:
            raise ValueError(
                "source_indices for metadata must be a non-empty 1D array"
            )

        with h5py.File(self.info.path, "r") as h5:
            return {
                name: _read_h5_rows(
                    h5["meta/%s" % name],
                    source_indices,
                )
                for name in (
                    "trajectory_id",
                    "element_id",
                    "integration_point",
                    "rve_id",
                    "load_group_code",
                    "case_code",
                    "split_code",
                    "reversal_step",
                )
            }


def _read_h5_rows(
    dataset: h5py.Dataset,
    source_indices: np.ndarray,
) -> np.ndarray:
    """
    Read arbitrary first-axis rows while satisfying h5py's increasing-index
    requirement. Duplicate indices are also handled safely.
    """
    source_indices = np.asarray(source_indices, dtype=np.int64)
    unique_sorted, inverse = np.unique(
        source_indices,
        return_inverse=True,
    )
    selected = np.asarray(dataset[unique_sorted, ...])
    return selected[inverse, ...]


