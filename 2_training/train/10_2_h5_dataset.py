def assemble_model_inputs_numpy(
    F_end: np.ndarray,
    theta_start: np.ndarray,
    static_values: np.ndarray,
    info: PhaseH5Info,
) -> np.ndarray:
    """
    Assemble [F(9), static-inputs(4), theta(9)] without including weight.

    Accepted shapes
    ---------------
    Single trajectory:
        F_end, theta_start : [L, 9]
        static_values      : [5]
        output             : [L, 22]

    Batch:
        F_end, theta_start : [B, L, 9]
        static_values      : [B, 5]
        output             : [B, L, 22]
    """
    F_end = np.asarray(F_end, dtype=np.float32)
    theta_start = np.asarray(theta_start, dtype=np.float32)
    static_values = np.asarray(static_values, dtype=np.float32)

    if F_end.shape != theta_start.shape:
        raise ValueError(
            "F_end shape %s != theta_start shape %s"
            % (F_end.shape, theta_start.shape)
        )
    if F_end.shape[-1] != 9:
        raise ValueError("Last F/theta dimension must be 9")

    static_input_indices = np.asarray(
        info.static_input_indices,
        dtype=np.int64,
    )

    if F_end.ndim == 2:
        if static_values.shape != (5,):
            raise ValueError(
                "Single-trajectory static shape must be (5,), got %s"
                % (static_values.shape,)
            )
        length = F_end.shape[0]
        static_input = static_values[static_input_indices]
        static_time = np.broadcast_to(
            static_input[None, :],
            (length, 4),
        )
        x = np.concatenate(
            (F_end, static_time, theta_start),
            axis=1,
        )

    elif F_end.ndim == 3:
        batch, length, _ = F_end.shape
        if static_values.shape != (batch, 5):
            raise ValueError(
                "Batch static shape must be (%d,5), got %s"
                % (batch, static_values.shape)
            )
        static_input = static_values[:, static_input_indices]
        static_time = np.broadcast_to(
            static_input[:, None, :],
            (batch, length, 4),
        )
        x = np.concatenate(
            (F_end, static_time, theta_start),
            axis=2,
        )

    else:
        raise ValueError(
            "F_end must be rank 2 or 3, got rank %d" % F_end.ndim
        )

    if x.shape[-1] != INPUT_DIM:
        raise RuntimeError(
            "Assembled input dimension=%d, expected=%d"
            % (x.shape[-1], INPUT_DIM)
        )

    return np.ascontiguousarray(x, dtype=np.float32)


def extract_sample_weights(
    static_values: np.ndarray,
    info: PhaseH5Info,
) -> np.ndarray:
    static_values = np.asarray(static_values, dtype=np.float32)
    weights = np.asarray(
        static_values[..., info.sample_weight_index],
        dtype=np.float32,
    )
    if not np.isfinite(weights).all():
        raise ValueError("NaN/Inf found in Sample_Weight")
    if np.any(weights <= 0.0):
        raise ValueError("Sample_Weight must be positive")
    return np.ascontiguousarray(weights)


