def _decode_json_attr(
    h5: h5py.File,
    name: str,
    default: object,
) -> object:
    if name not in h5.attrs:
        return default

    raw = h5.attrs[name]
    if isinstance(raw, bytes):
        raw = raw.decode("utf-8")

    try:
        return json.loads(str(raw))
    except Exception as exc:
        raise ValueError(
            "Invalid JSON attribute %s=%r in %s"
            % (name, raw, h5.filename)
        ) from exc


def _as_string_tuple(value: object, attribute_name: str) -> Tuple[str, ...]:
    if not isinstance(value, (list, tuple)):
        raise ValueError(
            "%s must decode to a list/tuple, got %r"
            % (attribute_name, type(value).__name__)
        )
    return tuple(str(x) for x in value)


def _as_int_codebook(value: object, attribute_name: str) -> Dict[str, int]:
    """
    Normalize an H5 JSON codebook to the internal form:

        {"train": 0, "val": 1}

    Step-08 files may store codebooks in either direction:

        label -> integer code
        integer code -> label

    Both forms are accepted here. Ambiguous or malformed mappings still fail.
    """
    if not isinstance(value, dict):
        raise ValueError(
            "%s must decode to a dict, got %r"
            % (attribute_name, type(value).__name__)
        )

    if not value:
        return {}

    # Preferred/expected form: label -> integer code.
    forward: Dict[str, int] = {}
    forward_ok = True
    for key, raw_code in value.items():
        try:
            code = int(raw_code)
        except (TypeError, ValueError):
            forward_ok = False
            break
        forward[str(key)] = code

    if forward_ok:
        if len(set(forward.values())) != len(forward):
            raise ValueError(
                "%s contains duplicate integer codes: %r"
                % (attribute_name, value)
            )
        return forward

    # Also accept the reverse form: integer code -> label.
    reverse: Dict[str, int] = {}
    for raw_code, raw_label in value.items():
        try:
            code = int(raw_code)
        except (TypeError, ValueError) as exc:
            raise ValueError(
                "%s is neither label->code nor code->label: %r"
                % (attribute_name, value)
            ) from exc

        label = str(raw_label).strip()
        if not label:
            raise ValueError(
                "%s contains an empty label: %r"
                % (attribute_name, value)
            )
        if label in reverse:
            raise ValueError(
                "%s contains duplicate label %r: %r"
                % (attribute_name, label, value)
            )
        reverse[label] = code

    return reverse


def _dataset_nbytes(dataset: h5py.Dataset) -> int:
    count = int(np.prod(dataset.shape, dtype=np.int64))
    return count * int(np.dtype(dataset.dtype).itemsize)


def inspect_phase_h5(cfg=CFG) -> PhaseH5Info:
    """
    Strictly validate the Step-08 phase H5 schema.

    This function reads metadata and split indices only; it does not load the
    large dynamic datasets into RAM.
    """
    path = Path(cfg.H5_DATA_PATH)
    if not path.is_file():
        raise FileNotFoundError("Step-08 H5 does not exist: %s" % path)

    with h5py.File(path, "r") as h5:
        required_datasets = (
            "F_end",
            "theta_start",
            "sigma_end",
            "static",
            "meta/trajectory_id",
            "meta/element_id",
            "meta/integration_point",
            "meta/rve_id",
            "meta/load_group_code",
            "meta/case_code",
            "meta/split_code",
            "meta/reversal_step",
            "split/train_indices",
            "split/val_indices",
        )
        for name in required_datasets:
            if name not in h5:
                raise KeyError("Missing H5 dataset %s in %s" % (name, path))

        f_shape = tuple(int(x) for x in h5["F_end"].shape)
        theta_shape = tuple(int(x) for x in h5["theta_start"].shape)
        sigma_shape = tuple(int(x) for x in h5["sigma_end"].shape)
        static_shape = tuple(int(x) for x in h5["static"].shape)

        if len(f_shape) != 3 or f_shape[2] != 9:
            raise ValueError("F_end must be [N,L,9], got %s" % (f_shape,))
        if theta_shape != f_shape:
            raise ValueError(
                "theta_start shape %s does not match F_end %s"
                % (theta_shape, f_shape)
            )
        if sigma_shape != (f_shape[0], f_shape[1], TARGET_DIM):
            raise ValueError(
                "sigma_end must be [N,L,%d], got %s"
                % (TARGET_DIM, sigma_shape)
            )
        if static_shape != (f_shape[0], 5):
            raise ValueError(
                "static must be [N,5], got %s" % (static_shape,)
            )

        n = f_shape[0]
        sequence_length = f_shape[1]

        phase = str(h5.attrs.get("phase", "")).upper().strip()
        multiplier = int(h5.attrs.get("increment_multiplier", -1))
        sequence_length_attr = int(
            h5.attrs.get("sequence_length", sequence_length)
        )
        trajectory_count_attr = int(
            h5.attrs.get("trajectory_count", n)
        )

        if phase != str(cfg.PHASE).upper():
            raise ValueError(
                "H5 phase=%r, but config PHASE=%r" % (phase, cfg.PHASE)
            )
        if multiplier != int(cfg.MULTIPLIER):
            raise ValueError(
                "H5 multiplier=%d, but config MULTIPLIER=%d"
                % (multiplier, cfg.MULTIPLIER)
            )
        if sequence_length_attr != sequence_length:
            raise ValueError(
                "H5 sequence_length attribute=%d, actual=%d"
                % (sequence_length_attr, sequence_length)
            )
        if trajectory_count_attr != n:
            raise ValueError(
                "H5 trajectory_count attribute=%d, actual=%d"
                % (trajectory_count_attr, n)
            )
        if (
            cfg.REQUIRE_SEQUENCE_LENGTH_MATCH
            and sequence_length != int(cfg.expected_sequence_length)
        ):
            raise ValueError(
                "H5 sequence length=%d, config expects=%d"
                % (sequence_length, cfg.expected_sequence_length)
            )

        static_columns = _as_string_tuple(
            _decode_json_attr(
                h5,
                "static_columns_json",
                list(STATIC_COLUMNS_IN_H5),
            ),
            "static_columns_json",
        )

        model_input_order = _as_string_tuple(
            _decode_json_attr(
                h5,
                "model_input_order_json",
                list(INPUT_ORDER),
            ),
            "model_input_order_json",
        )

        target_order = _as_string_tuple(
            _decode_json_attr(
                h5,
                "target_order_json",
                list(TARGET_ORDER),
            ),
            "target_order_json",
        )

        if model_input_order != INPUT_ORDER:
            raise ValueError(
                "H5 model input order differs from 10_1_config.py.\n"
                "H5:     %s\nConfig: %s"
                % (model_input_order, INPUT_ORDER)
            )
        if target_order != TARGET_ORDER:
            raise ValueError(
                "H5 target order differs from 10_1_config.py.\n"
                "H5:     %s\nConfig: %s"
                % (target_order, TARGET_ORDER)
            )

        required_static_names = (
            "DTIME",
            "Temperature",
            "N_total",
            "N_diff",
            "Sample_Weight",
        )
        for name in required_static_names:
            if name not in static_columns:
                raise ValueError(
                    "Static column %s is absent from %s"
                    % (name, static_columns)
                )

        static_input_indices = tuple(
            int(static_columns.index(name))
            for name in (
                "DTIME",
                "Temperature",
                "N_total",
                "N_diff",
            )
        )
        sample_weight_index = int(static_columns.index("Sample_Weight"))

        if bool(h5.attrs.get("sample_weight_is_model_input", False)):
            raise ValueError(
                "Step-08 H5 unexpectedly marks Sample_Weight as a model input"
            )

        if not bool(h5.attrs.get("multiplier_isolated_dataset", False)):
            raise ValueError(
                "The H5 does not declare multiplier_isolated_dataset=True"
            )

        train_indices = np.asarray(
            h5["split/train_indices"][:],
            dtype=np.int64,
        )
        val_indices = np.asarray(
            h5["split/val_indices"][:],
            dtype=np.int64,
        )

        _validate_split_indices(
            train_indices=train_indices,
            val_indices=val_indices,
            trajectory_count=n,
        )

        split_codes = np.asarray(
            h5["meta/split_code"][:],
            dtype=np.int8,
        )
        if split_codes.shape != (n,):
            raise ValueError(
                "meta/split_code must have shape (%d,), got %s"
                % (n, split_codes.shape)
            )
        if not np.all(split_codes[train_indices] == 0):
            raise ValueError("Some train_indices do not have split_code=0")
        if not np.all(split_codes[val_indices] == 1):
            raise ValueError("Some val_indices do not have split_code=1")

        if int(train_indices.size + val_indices.size) != n:
            raise ValueError(
                "Train+val counts do not cover all trajectories: %d+%d != %d"
                % (train_indices.size, val_indices.size, n)
            )

        dtype_names = {
            np.dtype(h5[name].dtype).name
            for name in ("F_end", "theta_start", "sigma_end", "static")
        }
        if len(dtype_names) != 1:
            raise ValueError(
                "Core arrays use inconsistent dtypes: %s" % sorted(dtype_names)
            )
        dtype_name = next(iter(dtype_names))

        if cfg.FAIL_ON_NAN_OR_INF:
            # Do not scan the full large arrays here. Full finite checks were
            # performed in Step-08. Static values are small enough to validate
            # once because they include the sample weights.
            static_values = np.asarray(h5["static"][:], dtype=np.float64)
            if not np.isfinite(static_values).all():
                raise ValueError("NaN/Inf found in static dataset")
            weights = static_values[:, sample_weight_index]
            if cfg.FAIL_ON_NONPOSITIVE_WEIGHT and np.any(weights <= 0.0):
                bad = np.flatnonzero(weights <= 0.0)[:10]
                raise ValueError(
                    "Non-positive Sample_Weight at indices %s"
                    % bad.tolist()
                )

        group_codebook = _as_int_codebook(
            _decode_json_attr(h5, "group_codebook_json", {}),
            "group_codebook_json",
        )
        case_codebook = _as_int_codebook(
            _decode_json_attr(h5, "case_codebook_json", {}),
            "case_codebook_json",
        )
        split_codebook = _as_int_codebook(
            _decode_json_attr(
                h5,
                "split_codebook_json",
                {"train": 0, "val": 1},
            ),
            "split_codebook_json",
        )

        estimated_core_bytes = sum(
            _dataset_nbytes(h5[name])
            for name in ("F_end", "theta_start", "sigma_end", "static")
        )

    return PhaseH5Info(
        path=path,
        phase=phase,
        multiplier=multiplier,
        sequence_length=sequence_length,
        trajectory_count=n,
        train_count=int(train_indices.size),
        val_count=int(val_indices.size),
        dtype_name=dtype_name,
        static_columns=static_columns,
        input_order=model_input_order,
        target_order=target_order,
        sample_weight_index=sample_weight_index,
        static_input_indices=static_input_indices,
        group_codebook=group_codebook,
        case_codebook=case_codebook,
        split_codebook=split_codebook,
        estimated_core_bytes=estimated_core_bytes,
    )


def _validate_split_indices(
    train_indices: np.ndarray,
    val_indices: np.ndarray,
    trajectory_count: int,
) -> None:
    for name, indices in (
        ("train", train_indices),
        ("val", val_indices),
    ):
        if indices.ndim != 1:
            raise ValueError("%s indices must be one-dimensional" % name)
        if indices.size == 0:
            raise ValueError("%s indices are empty" % name)
        if np.any(indices < 0) or np.any(indices >= trajectory_count):
            raise ValueError(
                "%s indices contain values outside [0,%d)"
                % (name, trajectory_count)
            )
        if np.unique(indices).size != indices.size:
            raise ValueError("%s indices contain duplicates" % name)

    overlap = np.intersect1d(
        train_indices,
        val_indices,
        assume_unique=False,
    )
    if overlap.size:
        raise ValueError(
            "Train/val indices overlap. Examples: %s"
            % overlap[:10].tolist()
        )


def load_lcs_reference(cfg=CFG) -> LCSReference:
    path = Path(cfg.LCS_BASELINE_H5_PATH)
    if not path.is_file():
        raise FileNotFoundError("Step-09 LCS H5 does not exist: %s" % path)

    with h5py.File(path, "r") as h5:
        required = "training_reference/lcs_horizontal_line_pct"
        if required not in h5:
            raise KeyError("Missing %s in %s" % (required, path))

        phase = str(h5.attrs.get("phase", "")).upper().strip()
        multiplier = int(h5.attrs.get("increment_multiplier", -1))
        sequence_length = int(h5.attrs.get("sequence_length", -1))
        split = str(
            h5.attrs.get("primary_split_for_training_line", "")
        ).strip()
        metric = str(h5.attrs.get("primary_metric", "")).strip()
        first_step_policy = str(
            h5.attrs.get("first_step_policy", "")
        ).strip()
        line = float(h5[required][()])

    if phase != str(cfg.PHASE).upper():
        raise ValueError(
            "LCS phase=%r, config phase=%r" % (phase, cfg.PHASE)
        )
    if multiplier != int(cfg.MULTIPLIER):
        raise ValueError(
            "LCS multiplier=%d, config multiplier=%d"
            % (multiplier, cfg.MULTIPLIER)
        )
    if sequence_length != int(cfg.expected_sequence_length):
        raise ValueError(
            "LCS sequence length=%d, config expects=%d"
            % (sequence_length, cfg.expected_sequence_length)
        )
    if split != "val":
        raise ValueError(
            "The training dashboard requires a validation LCS line, got split=%r"
            % split
        )
    if metric != str(cfg.VALIDATION_METRIC):
        raise ValueError(
            "LCS metric=%r, config metric=%r"
            % (metric, cfg.VALIDATION_METRIC)
        )
    if first_step_policy != "exclude":
        raise ValueError(
            "Expected Step-09 first_step_policy='exclude', got %r"
            % first_step_policy
        )
    if not math.isfinite(line) or line < 0.0:
        raise ValueError("Invalid LCS horizontal line: %r" % line)

    return LCSReference(
        path=path,
        phase=phase,
        multiplier=multiplier,
        sequence_length=sequence_length,
        split=split,
        metric=metric,
        horizontal_line_pct=line,
        first_step_policy=first_step_policy,
    )


