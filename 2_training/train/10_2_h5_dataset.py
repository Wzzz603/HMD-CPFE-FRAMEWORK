def smoke_test_first_batch(cfg=CFG) -> None:
    """
    Read only a tiny H5 batch without loading the complete dataset into RAM.
    """
    info = inspect_phase_h5(cfg)
    lcs = load_lcs_reference(cfg)
    print_data_summary(info, lcs)

    with h5py.File(info.path, "r") as h5:
        train_indices = np.asarray(
            h5["split/train_indices"][:2],
            dtype=np.int64,
        )

    store = PhaseH5Store(info=info, access_mode="h5")
    try:
        dataset = TrajectoryDataset(
            store=store,
            source_indices=train_indices,
            split_name="smoke_train",
        )
        samples = dataset.__getitems__(list(range(len(dataset))))
        batch = torch.utils.data.default_collate(samples)

        print("Smoke batch x      :", tuple(batch["x"].shape))
        print("Smoke batch y      :", tuple(batch["y"].shape))
        print("Smoke batch weight :", tuple(batch["weight"].shape))
        print(
            "Smoke trajectory IDs:",
            batch["trajectory_index"].tolist(),
        )

        expected_x = (
            len(dataset),
            info.sequence_length,
            INPUT_DIM,
        )
        expected_y = (
            len(dataset),
            info.sequence_length,
            TARGET_DIM,
        )

        if tuple(batch["x"].shape) != expected_x:
            raise RuntimeError(
                "Smoke x shape %s != expected %s"
                % (tuple(batch["x"].shape), expected_x)
            )
        if tuple(batch["y"].shape) != expected_y:
            raise RuntimeError(
                "Smoke y shape %s != expected %s"
                % (tuple(batch["y"].shape), expected_y)
            )
        if not torch.isfinite(batch["x"]).all():
            raise RuntimeError("NaN/Inf found in smoke x")
        if not torch.isfinite(batch["y"]).all():
            raise RuntimeError("NaN/Inf found in smoke y")
        if torch.any(batch["weight"] <= 0):
            raise RuntimeError("Non-positive weight in smoke batch")

        print("Smoke test: PASS")
    finally:
        store.close()


