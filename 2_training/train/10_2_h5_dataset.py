"""
10_2_h5_dataset.py

Step-10 data access for the Step-08 phase H5 files.

Responsibilities
----------------
1. Read one phase at one increment multiplier only.
2. Reuse the train/validation indices already fixed by Step-08.
3. Assemble the 22 model inputs in the exact order:

       F_end(9)
       + [DTIME, Temperature, N_total, N_diff](4)
       + theta_start(9)

4. Keep Sample_Weight outside the model inputs.
5. Support:
       - full-sequence LSTM batches;
       - current-step-only baseline chunks for Linear/Ridge/Lasso.
6. Never perform a second increment-multiplier sampling.
7. Read the fixed validation LCS reference generated by Step-09.

The file imports 10_1_config.py dynamically because Python module names cannot
normally begin with a digit.
"""

