class TrajectoryDataset(Dataset):
    """
    One item is one complete trajectory.

    Returned item
    -------------
    {
        "x":                  float32 [L, 22],
        "y":                  float32 [L, 6],
        "weight":             float32 scalar,
        "trajectory_index":   int64 scalar
    }
    """

    def __init__(
        self,
        store: PhaseH5Store,
        source_indices: np.ndarray,
        split_name: str,
    ) -> None:
        self.store = store
        self.info = store.info
        self.split_name = str(split_name)

        self.source_indices = np.asarray(
            source_indices,
            dtype=np.int64,
        )

        if self.source_indices.ndim != 1:
            raise ValueError("source_indices must be one-dimensional")
        if self.source_indices.size == 0:
            raise ValueError("%s dataset is empty" % self.split_name)

    def __len__(self) -> int:
        return int(self.source_indices.size)

    def __getitem__(self, logical_index: int) -> Dict[str, torch.Tensor]:
        logical_index = int(logical_index)
        if logical_index < 0:
            logical_index += len(self)
        if logical_index < 0 or logical_index >= len(self):
            raise IndexError(logical_index)

        source_index = int(self.source_indices[logical_index])
        arrays = self.store.read_core_rows(
            np.asarray([source_index], dtype=np.int64)
        )

        x = assemble_model_inputs_numpy(
            F_end=arrays["F_end"][0],
            theta_start=arrays["theta_start"][0],
            static_values=arrays["static"][0],
            info=self.info,
        )
        y = np.ascontiguousarray(
            arrays["sigma_end"][0],
            dtype=np.float32,
        )
        weight = float(
            extract_sample_weights(
                arrays["static"][0],
                self.info,
            )
        )

        return {
            "x": torch.from_numpy(x),
            "y": torch.from_numpy(y),
            "weight": torch.tensor(weight, dtype=torch.float32),
            "trajectory_index": torch.tensor(
                source_index,
                dtype=torch.int64,
            ),
        }

    def __getitems__(
        self,
        logical_indices: Sequence[int],
    ) -> List[Dict[str, torch.Tensor]]:
        """
        Batched fetch used by recent PyTorch DataLoader versions.

        In H5 mode this converts many random per-trajectory reads into one
        sorted batched H5 read.
        """
        logical = np.asarray(logical_indices, dtype=np.int64)
        if logical.ndim != 1:
            raise ValueError("logical_indices must be one-dimensional")
        if logical.size == 0:
            return []
        if np.any(logical < 0) or np.any(logical >= len(self)):
            raise IndexError("logical index out of range")

        source_indices = self.source_indices[logical]
        arrays = self.store.read_core_rows(source_indices)

        x_batch = assemble_model_inputs_numpy(
            F_end=arrays["F_end"],
            theta_start=arrays["theta_start"],
            static_values=arrays["static"],
            info=self.info,
        )
        y_batch = np.ascontiguousarray(
            arrays["sigma_end"],
            dtype=np.float32,
        )
        weights = extract_sample_weights(
            arrays["static"],
            self.info,
        )

        result: List[Dict[str, torch.Tensor]] = []
        for i in range(source_indices.size):
            result.append({
                "x": torch.from_numpy(x_batch[i]),
                "y": torch.from_numpy(y_batch[i]),
                "weight": torch.tensor(
                    float(weights[i]),
                    dtype=torch.float32,
                ),
                "trajectory_index": torch.tensor(
                    int(source_indices[i]),
                    dtype=torch.int64,
                ),
            })
        return result


def _load_split_indices(
    info: PhaseH5Info,
    split_name: str,
    max_count: Optional[int],
    random_seed: int,
) -> np.ndarray:
    if split_name not in ("train", "val"):
        raise ValueError("split_name must be train or val")

    dataset_path = "split/%s_indices" % split_name
    with h5py.File(info.path, "r") as h5:
        indices = np.asarray(
            h5[dataset_path][:],
            dtype=np.int64,
        )

    if max_count is None or int(max_count) >= int(indices.size):
        return indices

    max_count = int(max_count)
    if max_count <= 0:
        raise ValueError("max_count must be positive or None")

    split_offset = 0 if split_name == "train" else 1_000_003
    rng = np.random.default_rng(int(random_seed) + split_offset)
    chosen_positions = rng.choice(
        indices.size,
        size=max_count,
        replace=False,
    )
    # Sorting the retained source indices improves H5 locality in non-shuffled
    # validation and makes debug subsets deterministic.
    selected = np.sort(indices[chosen_positions])
    return np.asarray(selected, dtype=np.int64)


def build_lstm_data_bundle(cfg=CFG) -> LSTMDataBundle:
    """
    Construct train/validation complete-trajectory DataLoaders.

    The fixed Step-08 split is reused. No split or multiplier resampling occurs.
    """
    info = inspect_phase_h5(cfg)
    lcs_reference = load_lcs_reference(cfg)

    train_indices = _load_split_indices(
        info=info,
        split_name="train",
        max_count=cfg.MAX_TRAIN_TRAJECTORIES,
        random_seed=cfg.RANDOM_SEED,
    )
    val_indices = _load_split_indices(
        info=info,
        split_name="val",
        max_count=cfg.MAX_VAL_TRAJECTORIES,
        random_seed=cfg.RANDOM_SEED,
    )

    store = PhaseH5Store(
        info=info,
        access_mode=cfg.DATA_ACCESS_MODE,
    )

    train_dataset = TrajectoryDataset(
        store=store,
        source_indices=train_indices,
        split_name="train",
    )
    val_dataset = TrajectoryDataset(
        store=store,
        source_indices=val_indices,
        split_name="val",
    )

    if (
        cfg.DATA_ACCESS_MODE == "ram"
        and int(cfg.NUM_WORKERS) > 0
        and os.name == "nt"
    ):
        warnings.warn(
            "DATA_ACCESS_MODE='ram' with NUM_WORKERS>0 on Windows can copy the "
            "full RAM store into worker processes. NUM_WORKERS=0 is strongly "
            "recommended.",
            RuntimeWarning,
        )

    pin_memory = bool(
        cfg.PIN_MEMORY
        and str(cfg.DEVICE).lower().startswith("cuda")
    )
    persistent_workers = bool(
        cfg.PERSISTENT_WORKERS
        and int(cfg.NUM_WORKERS) > 0
    )

    generator = torch.Generator()
    generator.manual_seed(int(cfg.RANDOM_SEED))

    common_loader_args = {
        "batch_size": int(cfg.BATCH_SIZE),
        "num_workers": int(cfg.NUM_WORKERS),
        "pin_memory": pin_memory,
        "persistent_workers": persistent_workers,
    }

    train_loader = DataLoader(
        train_dataset,
        shuffle=True,
        drop_last=bool(cfg.DROP_LAST_TRAIN_BATCH),
        generator=generator,
        **common_loader_args,
    )

    val_loader = DataLoader(
        val_dataset,
        shuffle=False,
        drop_last=False,
        **common_loader_args,
    )

    return LSTMDataBundle(
        info=info,
        lcs_reference=lcs_reference,
        train_dataset=train_dataset,
        val_dataset=val_dataset,
        train_loader=train_loader,
        val_loader=val_loader,
        train_generator=generator,
        store=store,
    )


