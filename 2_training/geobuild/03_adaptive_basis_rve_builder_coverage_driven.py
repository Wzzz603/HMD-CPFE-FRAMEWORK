def ask_continue(cfg: Config, all_met: bool) -> str:
    if cfg.AUTO_STOP_ENABLED and all_met:
        return "n"
    if not cfg.INTERACTIVE_MODE:
        return "y"
    while True:
        ans = input("Continue adding one more RVE? [y] continue / [n] stop / [a] auto mode: ").strip().lower()
        if ans in ("y", "n", "a"):
            return ans
        print("Please input y, n, or a.")


