def candidate_to_base_df(rve_id: int, neighbor_df: pd.DataFrame, phase_grid: np.ndarray,
                         ndiff: np.ndarray, cfg: Config, candidate_info: Dict) -> pd.DataFrame:
    phases = phase_grid_to_element_phase(neighbor_df, phase_grid)
    df = neighbor_df[["Element_ID", "i", "j", "k"]].copy()
    for col in ["cx", "cy", "cz"]:
        if col in neighbor_df.columns:
            df[col] = neighbor_df[col]
    df["RVE_ID"] = int(rve_id)
    df["Phase"] = phases.astype(int)
    df["N_total"] = cfg.N_TOTAL_NEIGHBORS
    df["N_diff"] = ndiff.astype(int)
    df["Eta"] = df["N_diff"] / float(cfg.N_TOTAL_NEIGHBORS)
    df["Ndiff_Group"] = df["N_diff"].apply(lambda x: ndiff_group(int(x), cfg.NDIFF_GROUPS))
    df["Generator_Type"] = candidate_info.get("family", "UNKNOWN")
    return df


def shape_penalty_from_df(df: pd.DataFrame, cfg: Config) -> float:
    """Mild penalty for extremely narrow or extremely broad Ndiff distributions."""
    # Penalize very large CV of Phase x Ndiff within candidate, but only mildly.
    counts = df.groupby(["Phase", "N_diff"]).size()
    full_index = pd.MultiIndex.from_product(
        [[cfg.BCC_PHASE_ID, cfg.HCP_PHASE_ID], range(0, cfg.N_TOTAL_NEIGHBORS + 1)],
        names=["Phase", "N_diff"]
    )
    full = pd.Series(0.0, index=full_index)
    full.loc[counts.index] = counts.astype(float)
    cv = float(full.std() / (full.mean() + 1e-12))
    return cv



def phasewise_pn_balance_cv(pn_counts: pd.Series, cfg: Config) -> Dict[str, float]:
    """Coefficient of variation of exact N_diff counts within each phase.

    Each phase is evaluated independently so no global BCC:HCP ratio is implied.
    Lower is better; zero means all 27 N_diff states in that phase have equal counts.
    """
    out = {}
    cvs = []

    for phase, label in [
        (cfg.BCC_PHASE_ID, "BCC"),
        (cfg.HCP_PHASE_ID, "HCP"),
    ]:
        vals = pn_counts.loc[phase].to_numpy(dtype=float)
        mean = float(np.mean(vals))

        if mean <= 0.0:
            cv = 0.0
        else:
            cv = float(np.std(vals) / (mean + 1.0e-12))

        out["CV_PN_%s" % label] = cv
        cvs.append(cv)

    out["CV_PN_PHASE_MEAN"] = float(np.mean(cvs)) if cvs else 0.0
    return out


def candidate_overcoverage_penalty(old_pn: pd.Series,
                                   candidate_pn: pd.Series,
                                   cfg: Config) -> float:
    """Penalize additions to states that were already overrepresented.

    For each phase, the old cumulative phase mean is used as the reference.
    States above (1 + tolerance) * phase_mean carry a surplus factor.
    Candidate elements added to those states contribute to the penalty.

    The result is normalized by the total candidate element count and is therefore
    comparable across candidates.
    """
    penalty_sum = 0.0
    candidate_total = float(candidate_pn.sum())

    if candidate_total <= 0.0:
        return 0.0

    tol = float(cfg.OVERCOVER_REL_TOL)

    for phase in [cfg.BCC_PHASE_ID, cfg.HCP_PHASE_ID]:
        old_sub = old_pn.loc[phase].astype(float)
        cand_sub = candidate_pn.loc[phase].astype(float)

        phase_mean = float(old_sub.mean())
        if phase_mean <= 0.0:
            # No previous information yet: do not penalize the first RVE.
            continue

        threshold = (1.0 + tol) * phase_mean

        for nd in old_sub.index:
            old_count = float(old_sub.loc[nd])
            added = float(cand_sub.loc[nd])

            if old_count <= threshold or added <= 0.0:
                continue

            # Relative surplus over the phase mean.
            surplus_ratio = (old_count - threshold) / (phase_mean + 1.0e-12)
            penalty_sum += added * surplus_ratio

    return float(penalty_sum / candidate_total)


def score_candidate(candidate_counts: Dict,
                    new_metrics: Dict[str, float],
                    old_counts: Dict,
                    old_metrics: Dict[str, float],
                    accepted_pn_vectors: List[np.ndarray],
                    cfg: Config) -> Tuple[float, Dict[str, float]]:
    d_cpn = new_metrics["C_PN"] - old_metrics.get("C_PN", 0.0)
    d_cpo = new_metrics["C_PO"] - old_metrics.get("C_PO", 0.0)
    d_rge4 = new_metrics.get("R_ge_4", 0.0) - old_metrics.get("R_ge_4", 0.0)

    old_pn = old_counts["PN"]
    cand_pn = candidate_counts["PN"]
    new_pn = old_pn.add(cand_pn, fill_value=0)

    # --------------------------------------------------------
    # A. Hard existence gain
    # --------------------------------------------------------
    old_zero = int((old_pn < int(cfg.EXISTENCE_MIN_COUNT)).sum())
    new_zero = int((new_pn < int(cfg.EXISTENCE_MIN_COUNT)).sum())
    newly_filled_states = int(old_zero - new_zero)

    # --------------------------------------------------------
    # B. Deficit reduction toward N_MIN_PHASE_NDIFF
    # --------------------------------------------------------
    old_deficit = float(
        sum(
            max(0.0, float(cfg.N_MIN_PHASE_NDIFF) - float(c))
            for c in old_pn.values
        )
    )
    new_deficit = float(
        sum(
            max(0.0, float(cfg.N_MIN_PHASE_NDIFF) - float(c))
            for c in new_pn.values
        )
    )

    deficit_reduction = old_deficit - new_deficit
    deficit_norm = float(
        len(old_pn) * max(1, int(cfg.N_MIN_PHASE_NDIFF))
    )
    deficit_reduction_fraction = deficit_reduction / deficit_norm

    # --------------------------------------------------------
    # C. Phase-wise raw-distribution balancing
    # --------------------------------------------------------
    old_balance = phasewise_pn_balance_cv(old_pn, cfg)
    new_balance = phasewise_pn_balance_cv(new_pn, cfg)

    old_balance_cv = float(old_balance["CV_PN_PHASE_MEAN"])
    new_balance_cv = float(new_balance["CV_PN_PHASE_MEAN"])

    # Positive is good.
    balance_improvement = old_balance_cv - new_balance_cv

    # Explicitly punish a candidate for adding many samples to states that were
    # already above the mean of their own phase.
    overcoverage_penalty = candidate_overcoverage_penalty(
        old_pn=old_pn,
        candidate_pn=cand_pn,
        cfg=cfg,
    )

    # --------------------------------------------------------
    # D. Existing coverage / diversity terms
    # --------------------------------------------------------
    m_gain = marginal_pn_gain(old_pn, cand_pn, cfg)

    cand_vec = pn_distribution_vector(cand_pn)
    sim_penalty = 0.0

    if accepted_pn_vectors:
        sim_penalty = max(
            cosine_similarity(cand_vec, v)
            for v in accepted_pn_vectors
        )

    score = (
        cfg.SCORE_W_NEW_STATE_FILL * float(newly_filled_states)
        + cfg.SCORE_W_PRIORITY_REPAIR * float(deficit_reduction_fraction)
        + cfg.SCORE_W_BALANCE_IMPROVEMENT * float(balance_improvement)
        + cfg.SCORE_W_CPN * d_cpn
        + cfg.SCORE_W_CPO * d_cpo
        + cfg.SCORE_W_RGE4 * d_rge4
        + cfg.SCORE_W_MARGINAL_PN * m_gain
        - cfg.SCORE_W_OVERCOVERAGE_PENALTY * float(overcoverage_penalty)
        - cfg.SCORE_W_SIMILARITY_PENALTY * sim_penalty
    )

    detail = {
        "d_C_PN": d_cpn,
        "d_C_PO": d_cpo,
        "d_R_ge_4": d_rge4,

        "newly_filled_PN_states": newly_filled_states,

        "PN_deficit_reduction": deficit_reduction,
        "PN_deficit_reduction_fraction": deficit_reduction_fraction,

        "old_phase_mean_CV": old_balance_cv,
        "new_phase_mean_CV": new_balance_cv,
        "phase_balance_improvement": balance_improvement,

        "overcoverage_penalty": overcoverage_penalty,

        "marginal_PN_gain": m_gain,
        "similarity_penalty": sim_penalty,
    }

    return float(score), detail

def build_one_candidate(rve_id: int,
                        neighbor_df: pd.DataFrame,
                        neighbor_lists: List[List[int]],
                        elem_id_to_pos: Dict[int, int],
                        current_counts: Dict,
                        current_metrics: Dict[str, float],
                        bcc_pool: pd.DataFrame,
                        hcp_pool: pd.DataFrame,
                        accepted_pn_vectors: List[np.ndarray],
                        cfg: Config,
                        rng: np.random.Generator,
                        candidate_no: int,
                        priority_stage: str = "none",
                        priority_targets: Optional[List[Tuple[int, int, int]]] = None
                        ) -> Tuple[pd.DataFrame, Dict, float, Dict]:

    priority_targets = list(priority_targets or [])

    if priority_targets:
        phase_grid, gen_info = generate_priority_repair_phase_field(
            cfg=cfg,
            rng=rng,
            stage=priority_stage,
            targets=priority_targets,
        )
    else:
        family = str(rng.choice(cfg.FAMILY_NAMES))
        phase_grid, gen_info = generate_candidate_phase_field(cfg, rng, family)

    phases = phase_grid_to_element_phase(neighbor_df, phase_grid)
    ndiff = compute_n_diff(phases, neighbor_lists, elem_id_to_pos)

    base_df = candidate_to_base_df(
        rve_id, neighbor_df, phase_grid, ndiff, cfg, gen_info
    )
    assigned_df = assign_orientations_stratified(
        base_df, current_counts, bcc_pool, hcp_pool, cfg, rng
    )

    cand_counts = counts_from_rve(
        assigned_df, cfg, bcc_pool, hcp_pool
    )
    new_counts = add_counts(current_counts, cand_counts)
    new_metrics = compute_metrics(new_counts, cfg)

    score, detail = score_candidate(
        cand_counts,
        new_metrics,
        current_counts,
        current_metrics,
        accepted_pn_vectors,
        cfg,
    )

    # Explicitly score how well this candidate serves the requested deficit states.
    if priority_targets:
        priority_gain = 0.0
        target_added = {}

        for phase, nd, need in priority_targets:
            added = float(cand_counts["PN"].loc[(int(phase), int(nd))])
            key = "%s_N%02d" % (phase_label(int(phase), cfg), int(nd))
            target_added[key] = added

            if priority_stage == "existence":
                # One existing center is enough to satisfy the hard existence target.
                priority_gain += 1.0 if added > 0 else 0.0
            else:
                priority_gain += min(added, max(float(need), 1.0)) / max(float(need), 1.0)

        repair_bonus = float(cfg.SCORE_W_PRIORITY_REPAIR) * float(priority_gain)
        score += repair_bonus

        detail["priority_repair_active"] = True
        detail["priority_stage"] = priority_stage
        detail["priority_target_count"] = len(priority_targets)
        detail["priority_target_added"] = target_added
        detail["priority_repair_gain"] = priority_gain
        detail["priority_repair_bonus"] = repair_bonus
    else:
        detail["priority_repair_active"] = False
        detail["priority_stage"] = "none"
        detail["priority_target_count"] = 0

    shape_pen = shape_penalty_from_df(assigned_df, cfg)
    score -= cfg.SCORE_W_SHAPE_PENALTY * shape_pen

    detail["shape_penalty"] = shape_pen
    detail["candidate_no"] = candidate_no
    detail["family"] = gen_info.get("family", "UNKNOWN")
    detail["hcp_fraction_actual"] = float(
        (phase_grid == cfg.HCP_PHASE_ID).sum()
    ) / float(phase_grid.size)
    detail["score"] = score
    detail.update({"new_" + k: v for k, v in new_metrics.items()})

    assigned_df["Candidate_Score"] = score
    return assigned_df, cand_counts, score, detail


def build_one_candidate_worker(args):
    """Multiprocessing wrapper for candidate evaluation.

    Each worker receives an independent random seed so candidate generation is
    reproducible and independent across CPU processes. This function is defined
    at module level to be picklable on Windows.
    """
    (rve_id, neighbor_df, neighbor_lists, elem_id_to_pos, current_counts,
     current_metrics, bcc_pool, hcp_pool, accepted_pn_vectors, cfg, seed,
     candidate_no, priority_stage, priority_targets) = args
    worker_rng = np.random.default_rng(int(seed))
    return build_one_candidate(
        rve_id=rve_id,
        neighbor_df=neighbor_df,
        neighbor_lists=neighbor_lists,
        elem_id_to_pos=elem_id_to_pos,
        current_counts=current_counts,
        current_metrics=current_metrics,
        bcc_pool=bcc_pool,
        hcp_pool=hcp_pool,
        accepted_pn_vectors=accepted_pn_vectors,
        cfg=cfg,
        rng=worker_rng,
        candidate_no=candidate_no,
        priority_stage=priority_stage,
        priority_targets=priority_targets,
    )


def evaluate_candidate_pool(rve_id: int,
                            neighbor_df: pd.DataFrame,
                            neighbor_lists: List[List[int]],
                            elem_id_to_pos: Dict[int, int],
                            current_counts: Dict,
                            current_metrics: Dict[str, float],
                            bcc_pool: pd.DataFrame,
                            hcp_pool: pd.DataFrame,
                            accepted_pn_vectors: List[np.ndarray],
                            cfg: Config,
                            rng: np.random.Generator) -> Tuple[Tuple[pd.DataFrame, Dict, Dict], List[Dict]]:
    """Evaluate candidate RVEs either serially or in parallel.

    Returns
    -------
    best : (candidate_df, candidate_counts, selected_detail)
    round_details : list of detail dictionaries for all candidates
    """
    n_candidates = int(cfg.CANDIDATES_PER_ROUND)
    n_workers = int(max(1, cfg.N_CPU_WORKERS))
    n_workers = min(n_workers, n_candidates, os.cpu_count() or 1)

    priority_stage, priority_targets = get_priority_pn_targets(
        current_counts, cfg, rve_id
    )

    if priority_targets:
        print(
            "Coverage-driven repair active: stage=%s, target states=%d"
            % (priority_stage, len(priority_targets))
        )
        preview = priority_targets[:12]
        print("  priority preview:", [
            "%s-N%d(need=%d)" % (phase_label(p, cfg), nd, need)
            for p, nd, need in preview
        ])
        if len(priority_targets) > len(preview):
            print("  ... plus %d more target states" % (len(priority_targets) - len(preview)))

    seeds = rng.integers(
        0, np.iinfo(np.uint32).max,
        size=n_candidates, dtype=np.uint32
    )

    tasks = [
        (
            rve_id, neighbor_df, neighbor_lists, elem_id_to_pos,
            current_counts, current_metrics,
            bcc_pool, hcp_pool, accepted_pn_vectors, cfg,
            int(seeds[c - 1]), c,
            priority_stage, priority_targets
        )
        for c in range(1, n_candidates + 1)
    ]

    best = None
    best_score = -1.0e100
    round_details: List[Dict] = []

    if n_workers <= 1:
        for task in tasks:
            cand_df, cand_counts, score, detail = build_one_candidate_worker(task)
            detail["Round_K"] = rve_id
            round_details.append(detail)
            if score > best_score:
                best_score = score
                best = (cand_df, cand_counts, detail)
    else:
        print("Evaluating %d candidates with %d CPU workers ..." % (n_candidates, n_workers))
        with ProcessPoolExecutor(max_workers=n_workers) as executor:
            futures = [executor.submit(build_one_candidate_worker, task) for task in tasks]
            done_count = 0
            for fut in as_completed(futures):
                cand_df, cand_counts, score, detail = fut.result()
                detail["Round_K"] = rve_id
                round_details.append(detail)
                done_count += 1
                if score > best_score:
                    best_score = score
                    best = (cand_df, cand_counts, detail)
                if done_count == n_candidates or done_count % max(1, n_candidates // 4) == 0:
                    print("  candidates finished: %d/%d" % (done_count, n_candidates))

    if best is None:
        raise RuntimeError("No candidate was generated in round %d." % rve_id)
    return best, round_details


