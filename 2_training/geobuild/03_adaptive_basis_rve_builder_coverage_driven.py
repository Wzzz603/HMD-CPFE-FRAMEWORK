def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def parse_neighbor_list(x) -> List[int]:
    if isinstance(x, list):
        return [int(v) for v in x]
    if isinstance(x, str):
        return [int(v) for v in ast.literal_eval(x)]
    raise ValueError("Unsupported Neighbor_List format: %r" % type(x))


def load_neighbor_map(path: str) -> pd.DataFrame:
    df = pd.read_csv(path)
    required = {"Element_ID", "i", "j", "k", "Neighbor_List"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError("Neighbor map missing columns: %s" % sorted(missing))
    df["Neighbor_List"] = df["Neighbor_List"].apply(parse_neighbor_list)
    df = df.sort_values("Element_ID").reset_index(drop=True)
    return df


def load_orientation_pool(path: str, phase_name: str, dummy_count: int, allow_dummy: bool) -> pd.DataFrame:
    if path and os.path.exists(path):
        df = pd.read_csv(path)
        required = {"Orientation_ID", "phi1", "Phi", "phi2"}
        missing = required - set(df.columns)
        if missing:
            raise ValueError("%s orientation pool missing columns: %s" % (phase_name, sorted(missing)))
        df = df[["Orientation_ID", "phi1", "Phi", "phi2"]].copy()
        df["Orientation_ID"] = df["Orientation_ID"].astype(str)
        return df

    if not allow_dummy:
        raise FileNotFoundError(
            "%s orientation pool not found. Set %s_ORIENTATION_POOL_CSV or enable dummy mode." %
            (phase_name, phase_name)
        )

    # Dummy pool: useful for testing the adaptive workflow only.
    # Euler angles are NaN so the user cannot accidentally use them as final orientations.
    return pd.DataFrame({
        "Orientation_ID": ["%s_%04d" % (phase_name, i + 1) for i in range(dummy_count)],
        "phi1": np.nan,
        "Phi": np.nan,
        "phi2": np.nan,
    })


def ndiff_group(n: int, groups: Tuple[Tuple[str, int, int], ...]) -> str:
    for name, lo, hi in groups:
        if lo <= int(n) <= hi:
            return name
    return "out_of_range"


