"""
03_adaptive_basis_rve_builder.py

Adaptive basis-RVE builder for 20x20x20 periodic CPFE training RVEs.

This version supports multi-core candidate evaluation and six Ndiff groups.

What this script does
---------------------
1. Reads a periodic element-neighbor map produced from the 20^3 template INP.
2. Generates multiple candidate periodic phase fields per round.
3. Calculates periodic N_diff for each candidate.
4. Temporarily assigns phase-specific orientation seeds according to current coverage gaps.
5. Evaluates four convergence/coverage metrics:
      C_PN          : Phase x exact-N_diff effective coverage
      C_PO          : Phase x Orientation effective coverage
      R_ge_4        : percentage of orientation seeds appearing in at least four Ndiff groups
      N_undercovered: number of Phase x N_diff states below the effective-count threshold

   Weight diagnostics are still printed and saved, but capped W95 is no longer
   used as a main convergence metric because rare BCC-high-N_diff states can
   keep raw weights very large under the prescribed BCC/HCP = 8:2 phase ratio.
6. Accepts the best candidate as the next RVE.
7. Saves one folder per accepted RVE, plus global coverage history and dashboard figures.

Important
---------
This script DOES NOT generate Abaqus INP files.
It only generates the information needed later for INP injection:
    Element_ID, Phase, N_diff, Eta, Orientation_ID, phi1, Phi, phi2, Sample_Weight, etc.

Expected orientation pool CSV format
------------------------------------
Columns required:
    Orientation_ID, phi1, Phi, phi2

Phase convention
----------------
    BCC = 1
    HCP = 9

Author: generated for CPFE adaptive basis-RVE workflow
"""

