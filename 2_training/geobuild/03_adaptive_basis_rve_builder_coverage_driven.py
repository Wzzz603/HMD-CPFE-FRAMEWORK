def stop_criteria_check(history: List[Dict], cfg: Config) -> Dict[str, bool]:
    if len(history) < 2:
        return {"CPN": False, "CPO": False, "RGE4": False, "UNDER": False, "ALL": False}
    last = history[-1]
    prev = history[-2]
    d_cpn = last["C_PN"] - prev["C_PN"]
    d_cpo = last["C_PO"] - prev["C_PO"]
    d_rge4 = last["R_ge_4"] - prev["R_ge_4"]
    under_reduction = int(prev["N_undercovered"] - last["N_undercovered"])
    flags = {
        "CPN": d_cpn < cfg.STOP_DCPN,
        "CPO": d_cpo < cfg.STOP_DCPO,
        "RGE4": d_rge4 < cfg.STOP_DRGE4,
        "UNDER": under_reduction <= cfg.STOP_DUNDERCOVERED_REDUCTION_MAX,
    }
    flags["ALL"] = all(flags.values())
    return flags


