def compute_weight_diagnostics(pn_counts: pd.Series, cfg: Config) -> Dict[str, float]:
    raw, used = compute_state_weights_raw_and_used(pn_counts, cfg)

    nonzero_mask = pn_counts > 0
    finite_raw = raw[nonzero_mask & raw.notna()]
    finite_used = used[nonzero_mask & used.notna()]

    if len(finite_raw):
        w95_raw = float(np.percentile(finite_raw.values, 95))
        wmax_raw = float(finite_raw.max())
    else:
        w95_raw = float("nan")
        wmax_raw = float("nan")

    if len(finite_used):
        w95_used = float(np.percentile(finite_used.values, 95))
        wmax_used = float(finite_used.max())
    else:
        w95_used = float("nan")
        wmax_used = float("nan")

    if bool(cfg.USE_WEIGHT_CAP):
        cap_hit_nonzero = int((finite_raw >= float(cfg.WEIGHT_CAP)).sum())
        n_nonzero = int(nonzero_mask.sum())
        cap_hit_ratio = float(cap_hit_nonzero) / float(n_nonzero) if n_nonzero else 0.0
    else:
        cap_hit_nonzero = 0
        cap_hit_ratio = 0.0

    zero_states = int((pn_counts <= 0).sum())
    undercovered_states = int((pn_counts < cfg.N_MIN_PHASE_NDIFF).sum())
    effective_states = int((pn_counts >= cfg.N_MIN_PHASE_NDIFF).sum())

    # Total count deficit toward the effective-count target.
    total_deficit = int(
        sum(max(0, int(cfg.N_MIN_PHASE_NDIFF) - int(c)) for c in pn_counts.values)
    )

    return {
        "W95": w95_used,
        "W95_capped": w95_used,       # backward-compatible column name
        "W95_used": w95_used,
        "Wmax": wmax_used,
        "Wmax_capped": wmax_used,     # backward-compatible column name
        "Wmax_used": wmax_used,
        "W95_raw": w95_raw,
        "Wmax_raw": wmax_raw,
        "Cap_hit_states": cap_hit_nonzero,
        "Cap_hit_ratio": cap_hit_ratio,
        "Zero_PN_states": zero_states,
        "N_undercovered": undercovered_states,
        "N_effectively_covered": effective_states,
        "PN_total_deficit": total_deficit,
    }


def compute_metrics(counts: Dict, cfg: Config) -> Dict[str, float]:
    pn = counts["PN"]
    po = counts["PO"]
    pog = counts["POG"]

    # C_PN: effective Phase x exact-N_diff coverage
    c_pn = float((pn >= cfg.N_MIN_PHASE_NDIFF).sum()) / float(len(pn))

    # C_PO: effective Phase x Orientation coverage
    c_po = float((po >= cfg.O_MIN_ORIENTATION).sum()) / float(len(po)) if len(po) else 0.0

    # Orientation-Ndiff_group decoupling: how many group classes each orientation covers.
    present = (pog >= cfg.G_MIN_ORI_GROUP).astype(int)
    group_counts = present.groupby(level=["Phase", "Orientation_ID"]).sum()
    denom = float(len(group_counts)) if len(group_counts) else 1.0
    n_groups = len(cfg.NDIFF_GROUPS)
    r_values = {}
    for n in range(2, n_groups + 1):
        r_values["R_ge_%d" % n] = float((group_counts >= n).sum()) / denom if len(group_counts) else 0.0
    mean_group_count = float(group_counts.mean()) if len(group_counts) else 0.0

    # Weight diagnostics. Capped W95 is diagnostic, not the fourth main convergence metric.
    wdiag = compute_weight_diagnostics(pn, cfg)

    # Helpful diagnostics
    pn_values = pn.values.astype(float)
    cv_pn = float(np.std(pn_values) / (np.mean(pn_values) + 1e-12))
    phase_balance = phasewise_pn_balance_cv(pn, cfg)

    out = {
        "C_PN": c_pn,
        "C_PO": c_po,
        "Mean_Group_Count": mean_group_count,
        "CV_PN": cv_pn,
        "CV_PN_BCC": phase_balance["CV_PN_BCC"],
        "CV_PN_HCP": phase_balance["CV_PN_HCP"],
        "CV_PN_PHASE_MEAN": phase_balance["CV_PN_PHASE_MEAN"],
    }
    out.update(r_values)
    # Backward-compatible alias used in older output columns.
    out["R_3"] = out.get("R_ge_3", 0.0)
    out.update(wdiag)
    return out

def prior_weight_for_state(phase: int, nd: int, cfg: Config) -> float:
    # All Phase x N_diff states are treated symmetrically.
    return cfg.PRIOR_DEFAULT


def marginal_pn_gain(old_pn: pd.Series, add_pn: pd.Series, cfg: Config) -> float:
    gain = 0.0
    c0 = 5.0
    for idx in old_pn.index:
        phase, nd = idx
        old = float(old_pn.loc[idx])
        add = float(add_pn.loc[idx]) if idx in add_pn.index else 0.0
        alpha = prior_weight_for_state(int(phase), int(nd), cfg)
        gain += alpha * (math.log(old + add + c0) - math.log(old + c0))
    return gain


def pn_distribution_vector(pn: pd.Series) -> np.ndarray:
    arr = pn.values.astype(float)
    s = arr.sum()
    if s <= 0:
        return np.zeros_like(arr)
    return arr / s


def cosine_similarity(a: np.ndarray, b: np.ndarray) -> float:
    denom = np.linalg.norm(a) * np.linalg.norm(b)
    if denom <= 0:
        return 0.0
    return float(np.dot(a, b) / denom)


