def build_pool_dict(bcc_pool: pd.DataFrame, hcp_pool: pd.DataFrame, cfg: Config) -> Dict[int, pd.DataFrame]:
    return {cfg.BCC_PHASE_ID: bcc_pool.copy(), cfg.HCP_PHASE_ID: hcp_pool.copy()}


def assign_orientations_stratified(base_df: pd.DataFrame,
                                   current_counts: Dict,
                                   bcc_pool: pd.DataFrame,
                                   hcp_pool: pd.DataFrame,
                                   cfg: Config,
                                   rng: np.random.Generator) -> pd.DataFrame:
    """
    Assign orientations after Phase and N_diff are fixed.

    Strategy:
    - Group elements by Phase x Ndiff_Group.
    - Within each group, prioritize orientation seeds with low total usage and low usage in that group.
    - Use round-robin to avoid over-concentrating one orientation in one group.
    """
    df = base_df.copy()
    df["Orientation_ID"] = ""
    df["phi1"] = np.nan
    df["Phi"] = np.nan
    df["phi2"] = np.nan

    pool_by_phase = build_pool_dict(bcc_pool, hcp_pool, cfg)
    po_counts = current_counts["PO"].copy()
    pog_counts = current_counts["POG"].copy()

    for phase in [cfg.BCC_PHASE_ID, cfg.HCP_PHASE_ID]:
        pool = pool_by_phase[phase]
        pool_ids = pool["Orientation_ID"].astype(str).tolist()
        pool_lookup = pool.set_index("Orientation_ID")

        for gname, _, _ in cfg.NDIFF_GROUPS:
            mask = (df["Phase"] == phase) & (df["Ndiff_Group"] == gname)
            idxs = df.index[mask].tolist()
            if not idxs:
                continue
            rng.shuffle(idxs)

            # Lower score = higher priority.
            orient_scores = []
            for oid in pool_ids:
                total_use = float(po_counts.loc[(phase, oid)]) if (phase, oid) in po_counts.index else 0.0
                group_use = float(pog_counts.loc[(phase, oid, gname)]) if (phase, oid, gname) in pog_counts.index else 0.0
                # total and group terms; group gets more weight to improve Orientation x Ndiff_group decoupling
                score = total_use + 2.5 * group_use + rng.uniform(0.0, 0.01)
                orient_scores.append((score, oid))
            orient_scores.sort(key=lambda x: x[0])
            ordered_ids = [oid for _, oid in orient_scores]

            # Round-robin through priority list.
            for local_i, row_idx in enumerate(idxs):
                oid = ordered_ids[local_i % len(ordered_ids)]
                vals = pool_lookup.loc[oid]
                df.at[row_idx, "Orientation_ID"] = oid
                df.at[row_idx, "phi1"] = vals["phi1"]
                df.at[row_idx, "Phi"] = vals["Phi"]
                df.at[row_idx, "phi2"] = vals["phi2"]

                # update local counts so this candidate does not overuse the same orientation too much
                po_counts.loc[(phase, oid)] = po_counts.loc[(phase, oid)] + 1
                pog_counts.loc[(phase, oid, gname)] = pog_counts.loc[(phase, oid, gname)] + 1

    return df


