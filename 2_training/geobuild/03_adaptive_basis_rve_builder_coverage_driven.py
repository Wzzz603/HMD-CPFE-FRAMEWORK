def exact_hcp_threshold(field: np.ndarray, hcp_count: int) -> np.ndarray:
    """Return boolean mask with exactly hcp_count True values at the largest field values."""
    flat = field.ravel()
    if hcp_count <= 0 or hcp_count >= flat.size:
        raise ValueError("Invalid hcp_count: %d" % hcp_count)
    idx = np.argpartition(flat, -hcp_count)[-hcp_count:]
    mask = np.zeros(flat.size, dtype=bool)
    mask[idx] = True
    return mask.reshape(field.shape)


def periodic_distance_sq_grid(nx: int, ny: int, nz: int, cx: float, cy: float, cz: float) -> np.ndarray:
    x = np.arange(nx)[:, None, None]
    y = np.arange(ny)[None, :, None]
    z = np.arange(nz)[None, None, :]
    dx = np.minimum(np.abs(x - cx), nx - np.abs(x - cx))
    dy = np.minimum(np.abs(y - cy), ny - np.abs(y - cy))
    dz = np.minimum(np.abs(z - cz), nz - np.abs(z - cz))
    return dx * dx + dy * dy + dz * dz


def generate_cluster_field(nx: int, ny: int, nz: int, rng: np.random.Generator,
                           n_centers: int = 3, radius: float = 4.0) -> np.ndarray:
    field = np.zeros((nx, ny, nz), dtype=float)
    for _ in range(n_centers):
        cx = rng.uniform(0, nx)
        cy = rng.uniform(0, ny)
        cz = rng.uniform(0, nz)
        dist2 = periodic_distance_sq_grid(nx, ny, nz, cx, cy, cz)
        field += np.exp(-dist2 / (2.0 * radius * radius))
    field += 0.05 * rng.normal(size=(nx, ny, nz))
    return field


def generate_candidate_phase_field(cfg: Config, rng: np.random.Generator, family: str) -> Tuple[np.ndarray, Dict]:
    """Generate one candidate phase array without imposing a physical phase ratio.

    A broad random HCP fraction is used only as a background-topology generator.
    It is not a material constraint and is not rebalanced after targeted motifs
    are inserted.
    """
    nx, ny, nz = cfg.NX, cfg.NY, cfg.NZ
    n_elem = nx * ny * nz

    fmin = float(cfg.RANDOM_HCP_FRACTION_MIN)
    fmax = float(cfg.RANDOM_HCP_FRACTION_MAX)
    if not (0.0 < fmin < fmax < 1.0):
        raise ValueError("Require 0 < RANDOM_HCP_FRACTION_MIN < RANDOM_HCP_FRACTION_MAX < 1.")

    hcp_fraction = float(rng.uniform(fmin, fmax))
    hcp_count = int(round(n_elem * hcp_fraction))
    hcp_count = max(1, min(n_elem - 1, hcp_count))

    info = {
        "family": family,
        "background_hcp_fraction_requested": hcp_fraction,
    }

    if family == "HCP_CLUSTERED":
        field = generate_cluster_field(
            nx, ny, nz, rng,
            n_centers=int(rng.integers(1, 3)),
            radius=float(rng.uniform(3.8, 5.8))
        )

    elif family == "BCC_CLUSTERED":
        # Negating the field makes the clustered low-field region preferentially BCC.
        field = -generate_cluster_field(
            nx, ny, nz, rng,
            n_centers=int(rng.integers(1, 3)),
            radius=float(rng.uniform(3.8, 5.8))
        )

    elif family == "MEDIUM_CLUSTERED":
        if gaussian_filter is None:
            field = rng.normal(size=(nx, ny, nz))
        else:
            field = gaussian_filter(
                rng.normal(size=(nx, ny, nz)),
                sigma=float(rng.choice([1.6, 2.0, 2.4])),
                mode="wrap"
            )

    elif family == "INTERFACE_ENRICHED":
        if gaussian_filter is None:
            field = rng.normal(size=(nx, ny, nz))
        else:
            field = gaussian_filter(
                rng.normal(size=(nx, ny, nz)),
                sigma=float(rng.choice([0.7, 0.9, 1.1])),
                mode="wrap"
            )

    elif family == "MIXED_FRAGMENTED":
        if gaussian_filter is None:
            field = rng.normal(size=(nx, ny, nz))
        else:
            field1 = gaussian_filter(rng.normal(size=(nx, ny, nz)), sigma=2.5, mode="wrap")
            field2 = gaussian_filter(rng.normal(size=(nx, ny, nz)), sigma=0.6, mode="wrap")
            field = 0.65 * field1 + 0.35 * field2

    elif family == "BCC_IN_HCP_INCLUSION":
        field = generate_cluster_field(
            nx, ny, nz, rng,
            n_centers=int(rng.integers(1, 3)),
            radius=float(rng.uniform(4.0, 6.0))
        )
        prelim = exact_hcp_threshold(field, hcp_count)
        hcp_positions = np.argwhere(prelim)
        if len(hcp_positions) > 0:
            for _ in range(int(rng.integers(4, 10))):
                px, py, pz = hcp_positions[int(rng.integers(0, len(hcp_positions)))]
                dist2 = periodic_distance_sq_grid(nx, ny, nz, px, py, pz)
                pocket_radius = float(rng.uniform(0.8, 1.5))
                field -= float(rng.uniform(0.8, 1.4)) * np.exp(
                    -dist2 / (2.0 * pocket_radius * pocket_radius)
                )

    else:
        sigma = float(rng.choice(cfg.SIGMA_LIST))
        info["sigma"] = sigma
        if gaussian_filter is None:
            field = rng.normal(size=(nx, ny, nz))
        else:
            field = gaussian_filter(rng.normal(size=(nx, ny, nz)), sigma=sigma, mode="wrap")

    hcp_mask = exact_hcp_threshold(field, hcp_count)
    phase = np.full((nx, ny, nz), cfg.BCC_PHASE_ID, dtype=np.int16)
    phase[hcp_mask] = cfg.HCP_PHASE_ID

    info["hcp_count"] = int(hcp_mask.sum())
    info["bcc_count"] = int(n_elem - hcp_mask.sum())
    info["hcp_fraction_actual"] = float(hcp_mask.mean())
    return phase, info


def periodic_chebyshev_distance(a: Tuple[int, int, int], b: Tuple[int, int, int],
                                nx: int, ny: int, nz: int) -> int:
    """Periodic Chebyshev distance between two integer grid points."""
    dx = min(abs(a[0] - b[0]), nx - abs(a[0] - b[0]))
    dy = min(abs(a[1] - b[1]), ny - abs(a[1] - b[1]))
    dz = min(abs(a[2] - b[2]), nz - abs(a[2] - b[2]))
    return int(max(dx, dy, dz))


def neighbor_offsets_26() -> List[Tuple[int, int, int]]:
    return [(di, dj, dk)
            for dk in (-1, 0, 1)
            for dj in (-1, 0, 1)
            for di in (-1, 0, 1)
            if not (di == 0 and dj == 0 and dk == 0)]


def choose_repair_centers(cfg: Config,
                          rng: np.random.Generator,
                          n_centers: int) -> List[Tuple[int, int, int]]:
    """Choose separated motif centers using periodic Chebyshev distance."""
    centers: List[Tuple[int, int, int]] = []
    max_trials = max(20000, 500 * int(n_centers))

    for _ in range(max_trials):
        if len(centers) >= int(n_centers):
            break

        c = (
            int(rng.integers(0, cfg.NX)),
            int(rng.integers(0, cfg.NY)),
            int(rng.integers(0, cfg.NZ)),
        )

        if all(
            periodic_chebyshev_distance(
                c, old, cfg.NX, cfg.NY, cfg.NZ
            ) >= int(cfg.REPAIR_MIN_CENTER_DISTANCE)
            for old in centers
        ):
            centers.append(c)

    if len(centers) < int(n_centers):
        raise RuntimeError(
            "Could not place %d non-overlapping targeted motifs with "
            "REPAIR_MIN_CENTER_DISTANCE=%d. Placed only %d."
            % (int(n_centers), int(cfg.REPAIR_MIN_CENTER_DISTANCE), len(centers))
        )

    return centers


def get_priority_pn_targets(current_counts: Dict,
                            cfg: Config,
                            round_k: int) -> Tuple[str, List[Tuple[int, int, int]]]:
    """Return coverage-driven target states for the next candidate RVE.

    Returns
    -------
    stage : "existence", "balance", "equalize", or "none"
    targets : [(phase, N_diff, need), ...]

    Existence stage:
        Every Phase x exact-N_diff state must reach EXISTENCE_MIN_COUNT.
        Missing states are targeted before any balancing objective.

    Balance stage:
        Once all states exist, the states with the smallest cumulative counts are
        prioritized toward N_MIN_PHASE_NDIFF.

    Equalize stage:
        Once all states reach N_MIN_PHASE_NDIFF, states that remain substantially
        below the mean count of their own phase are preferentially targeted.
    """
    if not cfg.PRIORITY_REPAIR_ENABLED:
        return "none", []
    if int(round_k) < int(cfg.PRIORITY_REPAIR_START_ROUND):
        return "none", []

    pn = current_counts["PN"]

    missing: List[Tuple[int, int, int, int]] = []
    for (phase, nd), value in pn.items():
        c = int(value)
        if c < int(cfg.EXISTENCE_MIN_COUNT):
            need = int(cfg.EXISTENCE_MIN_COUNT) - c
            missing.append((c, int(nd), int(phase), need))

    if missing:
        # Lower current count first; then N_diff; then phase for deterministic ordering.
        missing.sort(key=lambda x: (x[0], x[1], x[2]))
        selected = missing[:int(cfg.MAX_EXISTENCE_TARGETS_PER_RVE)]
        targets = [(phase, nd, need) for _, nd, phase, need in selected]
        return "existence", targets

    under: List[Tuple[int, int, int, int]] = []
    for (phase, nd), value in pn.items():
        c = int(value)
        if c < int(cfg.N_MIN_PHASE_NDIFF):
            need = int(cfg.N_MIN_PHASE_NDIFF) - c
            under.append((c, int(nd), int(phase), need))

    if under:
        # The least-covered states are always served first.
        under.sort(key=lambda x: (x[0], x[1], x[2]))
        selected = under[:int(cfg.MAX_BALANCE_TARGETS_PER_RVE)]
        targets = [(phase, nd, need) for _, nd, phase, need in selected]
        return "balance", targets

    # Relative equalization stage:
    # all states already satisfy N_MIN_PHASE_NDIFF, but some states may still be
    # much lower than the mean count of their own phase.
    equalize: List[Tuple[float, int, int, int]] = []
    tol = float(cfg.EQUALIZE_REL_TOL)

    for phase in [cfg.BCC_PHASE_ID, cfg.HCP_PHASE_ID]:
        sub = pn.loc[phase]
        phase_mean = float(sub.mean())

        if phase_mean <= 0.0:
            continue

        target_level = (1.0 - tol) * phase_mean

        for nd, value in sub.items():
            c = float(value)

            if c < target_level:
                need = max(1, int(math.ceil(target_level - c)))
                relative_level = c / (phase_mean + 1.0e-12)
                equalize.append(
                    (relative_level, int(nd), int(phase), int(need))
                )

    if equalize:
        # Smallest relative count first, independently of the global phase ratio.
        equalize.sort(key=lambda x: (x[0], x[1], x[2]))
        selected = equalize[:int(cfg.MAX_EQUALIZE_TARGETS_PER_RVE)]
        targets = [(phase, nd, need) for _, nd, phase, need in selected]
        return "equalize", targets

    return "none", []


def build_target_motif_requests(stage: str,
                                targets: List[Tuple[int, int, int]],
                                cfg: Config) -> List[Tuple[int, int, int]]:
    """Expand target states into individual motif requests.

    Each request is (phase, N_diff, target_need).
    """
    requests: List[Tuple[int, int, int]] = []

    for phase, nd, need in targets:
        if stage == "existence":
            n_motifs = int(cfg.EXISTENCE_MOTIFS_PER_STATE)
        else:
            n_motifs = min(
                int(cfg.BALANCE_MAX_MOTIFS_PER_STATE),
                max(1, int(need)),
            )

        for _ in range(n_motifs):
            requests.append((int(phase), int(nd), int(need)))

    return requests


def generate_priority_repair_phase_field(cfg: Config,
                                         rng: np.random.Generator,
                                         stage: str,
                                         targets: List[Tuple[int, int, int]]) -> Tuple[np.ndarray, Dict]:
    """Generate one phase field that explicitly embeds multiple deficient states.

    A target motif is a 3x3x3 periodic block whose center has the requested phase
    and whose 26 neighbors contain exactly target_ndiff opposite-phase cells.
    Motifs are separated so one motif cannot overwrite another motif's center
    neighborhood. No phase-fraction rebalance is applied afterward.
    """
    background_family = str(rng.choice(cfg.FAMILY_NAMES))
    phase, base_info = generate_candidate_phase_field(cfg, rng, background_family)

    requests = build_target_motif_requests(stage, targets, cfg)
    if not requests:
        return phase, base_info

    centers = choose_repair_centers(cfg, rng, len(requests))
    offsets = neighbor_offsets_26()

    target_records = []

    for center, (target_phase, target_ndiff, target_need) in zip(centers, requests):
        if not (0 <= int(target_ndiff) <= int(cfg.N_TOTAL_NEIGHBORS)):
            raise ValueError("target_ndiff must be in [0, 26].")

        other_phase = (
            cfg.HCP_PHASE_ID
            if int(target_phase) == int(cfg.BCC_PHASE_ID)
            else cfg.BCC_PHASE_ID
        )

        ci, cj, ck = center
        phase[ci, cj, ck] = int(target_phase)

        # Randomize which neighbor directions are opposite phase.
        order = np.arange(len(offsets))
        rng.shuffle(order)
        other_idx = set(int(x) for x in order[:int(target_ndiff)])

        for m, (di, dj, dk) in enumerate(offsets):
            ni = (ci + di) % cfg.NX
            nj = (cj + dj) % cfg.NY
            nk = (ck + dk) % cfg.NZ
            phase[ni, nj, nk] = (
                int(other_phase) if m in other_idx else int(target_phase)
            )

        target_records.append({
            "phase": int(target_phase),
            "N_diff": int(target_ndiff),
            "need_before_candidate": int(target_need),
            "center": [int(ci), int(cj), int(ck)],
        })

    n_elem = int(cfg.NX * cfg.NY * cfg.NZ)
    hcp_count = int((phase == cfg.HCP_PHASE_ID).sum())

    info = {
        "family": "COVERAGE_DRIVEN_TARGETED",
        "background_family": base_info.get("family", background_family),
        "priority_stage": stage,
        "n_target_states": int(len(targets)),
        "n_target_motifs": int(len(requests)),
        "target_records": target_records,
        "hcp_count": hcp_count,
        "bcc_count": n_elem - hcp_count,
        "hcp_fraction_actual": float(hcp_count) / float(n_elem),
    }
    return phase, info


def phase_grid_to_element_phase(neighbor_df: pd.DataFrame, phase_grid: np.ndarray) -> np.ndarray:
    phases = np.empty(len(neighbor_df), dtype=np.int16)
    for row_i, row in neighbor_df.iterrows():
        phases[row_i] = phase_grid[int(row["i"]), int(row["j"]), int(row["k"])]
    return phases


def compute_n_diff(phases: np.ndarray, neighbor_lists: List[List[int]], elem_id_to_pos: Dict[int, int]) -> np.ndarray:
    ndiff = np.zeros(len(phases), dtype=np.int16)
    for pos, nbr_ids in enumerate(neighbor_lists):
        p = phases[pos]
        cnt = 0
        for nid in nbr_ids:
            npos = elem_id_to_pos[int(nid)]
            if phases[npos] != p:
                cnt += 1
        ndiff[pos] = cnt
    return ndiff


