def update_sample_weights(all_rve_dfs: List[pd.DataFrame], global_counts: Dict, cfg: Config) -> List[pd.DataFrame]:
    state_weights = compute_state_weights_from_pn(global_counts["PN"], cfg)
    out = []
    for df in all_rve_dfs:
        d = df.copy()
        d["Sample_Weight"] = [float(state_weights.loc[(int(p), int(n))]) for p, n in zip(d["Phase"], d["N_diff"])]
        out.append(d)
    return out


def save_rve_folder(df: pd.DataFrame, rve_index: int, out_root: Path, metrics: Dict, detail: Dict) -> None:
    folder = out_root / ("RVE_%03d" % rve_index)
    ensure_dir(folder)
    df.to_csv(folder / "rve_master.csv", index=False)
    df[["RVE_ID", "Element_ID", "i", "j", "k", "Phase", "N_total", "N_diff", "Eta", "Ndiff_Group"]].to_csv(
        folder / "phase_topology.csv", index=False
    )
    df[["RVE_ID", "Element_ID", "Phase", "N_diff", "Ndiff_Group", "Orientation_ID", "phi1", "Phi", "phi2", "Sample_Weight"]].to_csv(
        folder / "inp_injection_table.csv", index=False
    )
    df.groupby(["Phase", "N_diff"]).size().reset_index(name="Count").to_csv(folder / "phase_ndiff_counts.csv", index=False)
    info = {
        "RVE_Index": rve_index,
        "Metrics_after_acceptance": metrics,
        "Candidate_detail": detail,
        "Columns_for_later_inp_injection": [
            "Element_ID", "Phase", "N_total", "N_diff", "Eta", "Orientation_ID", "phi1", "Phi", "phi2", "Sample_Weight"
        ],
        "Note": "This folder does not contain an Abaqus INP. It contains element-level information to be injected into a 20^3 template INP later."
    }
    with open(folder / "rve_info.json", "w", encoding="utf-8") as f:
        json.dump(info, f, indent=2, ensure_ascii=False)


def save_global_outputs(out_root: Path, all_rve_dfs: List[pd.DataFrame], global_counts: Dict,
                        history: List[Dict], candidate_details: List[Dict], cfg: Config) -> None:
    if all_rve_dfs:
        pd.concat(all_rve_dfs, ignore_index=True).to_csv(out_root / "RVE_all_master_current.csv", index=False)
    pd.DataFrame(history).to_csv(out_root / "coverage_history.csv", index=False)
    pd.DataFrame(candidate_details).to_csv(out_root / "candidate_scores_all_rounds.csv", index=False)
    global_counts["PN"].reset_index(name="Count").to_csv(out_root / "cumulative_phase_ndiff_counts.csv", index=False)
    global_counts["PO"].reset_index(name="Count").to_csv(out_root / "cumulative_phase_orientation_counts.csv", index=False)
    global_counts["POG"].reset_index(name="Count").to_csv(out_root / "cumulative_orientation_ndiff_group_counts.csv", index=False)

    # Extra diagnostics for later publication-style plots:
    # before/after weighting balance and orientation distribution checks.
    raw_w, used_w = compute_state_weights_raw_and_used(global_counts["PN"], cfg)
    diag = global_counts["PN"].reset_index(name="Count")
    diag["Weight_Raw"] = [
        float(raw_w.loc[(int(p), int(n))])
        if pd.notna(raw_w.loc[(int(p), int(n))]) else np.nan
        for p, n in zip(diag["Phase"], diag["N_diff"])
    ]
    diag["Weight_Used"] = [
        float(used_w.loc[(int(p), int(n))])
        if pd.notna(used_w.loc[(int(p), int(n))]) else np.nan
        for p, n in zip(diag["Phase"], diag["N_diff"])
    ]
    # Backward-compatible column name for old plotting scripts.
    diag["Weight_Capped"] = diag["Weight_Used"]
    diag["Effective_Covered"] = diag["Count"] >= cfg.N_MIN_PHASE_NDIFF
    diag["Undercovered"] = diag["Count"] < cfg.N_MIN_PHASE_NDIFF
    diag.to_csv(out_root / "cumulative_phase_ndiff_weight_diagnostics.csv", index=False)

    present = (global_counts["POG"] >= cfg.G_MIN_ORI_GROUP).astype(int)
    group_counts = present.groupby(level=["Phase", "Orientation_ID"]).sum().reset_index(name="Covered_Group_Count")
    group_counts.to_csv(out_root / "cumulative_orientation_group_coverage_summary.csv", index=False)


