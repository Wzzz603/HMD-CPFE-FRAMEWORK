def main(cfg: Config = CFG) -> None:
    random.seed(cfg.RANDOM_SEED)
    rng = np.random.default_rng(cfg.RANDOM_SEED)

    out_root = Path(cfg.OUTPUT_ROOT)
    if cfg.CLEAR_OUTPUT_ROOT_ON_START and out_root.exists():
        shutil.rmtree(out_root)
    ensure_dir(out_root)

    print("Reading periodic neighbor map:", cfg.NEIGHBOR_MAP_CSV)
    neighbor_df = load_neighbor_map(cfg.NEIGHBOR_MAP_CSV)
    n_elem = len(neighbor_df)
    expected = cfg.NX * cfg.NY * cfg.NZ
    if n_elem != expected:
        print("WARNING: neighbor map has %d elements, but NX*NY*NZ = %d" % (n_elem, expected))

    neighbor_lists = neighbor_df["Neighbor_List"].tolist()
    elem_id_to_pos = {int(eid): pos for pos, eid in enumerate(neighbor_df["Element_ID"].tolist())}

    bcc_pool = load_orientation_pool(cfg.BCC_ORIENTATION_POOL_CSV, "BCC", cfg.DUMMY_BCC_ORIENTATION_COUNT, cfg.ALLOW_DUMMY_ORIENTATION_POOL)
    hcp_pool = load_orientation_pool(cfg.HCP_ORIENTATION_POOL_CSV, "HCP", cfg.DUMMY_HCP_ORIENTATION_COUNT, cfg.ALLOW_DUMMY_ORIENTATION_POOL)

    if bcc_pool[["phi1", "Phi", "phi2"]].isna().any().any() or hcp_pool[["phi1", "Phi", "phi2"]].isna().any().any():
        print("WARNING: Dummy or incomplete orientation pool detected. This is OK for workflow testing, but NOT for final INP injection.")

    # Save config snapshot
    with open(out_root / "builder_config_snapshot.json", "w", encoding="utf-8") as f:
        json.dump(cfg.__dict__, f, indent=2, ensure_ascii=False)

    global_counts = empty_counts(cfg, bcc_pool, hcp_pool)
    current_metrics = compute_metrics(global_counts, cfg)
    all_rve_dfs: List[pd.DataFrame] = []
    accepted_details: List[Dict] = []
    accepted_pn_vectors: List[np.ndarray] = []
    history: List[Dict] = []
    all_candidate_details: List[Dict] = []

    auto_mode = not cfg.INTERACTIVE_MODE

    for k in range(1, cfg.MAX_RVE_COUNT + 1):
        print("\nGenerating candidate pool for RVE #%d ..." % k)
        best, round_details = evaluate_candidate_pool(
            rve_id=k,
            neighbor_df=neighbor_df,
            neighbor_lists=neighbor_lists,
            elem_id_to_pos=elem_id_to_pos,
            current_counts=global_counts,
            current_metrics=current_metrics,
            bcc_pool=bcc_pool,
            hcp_pool=hcp_pool,
            accepted_pn_vectors=accepted_pn_vectors,
            cfg=cfg,
            rng=rng,
        )
        selected_df, selected_counts, selected_detail = best

        # Accept the best candidate
        global_counts = add_counts(global_counts, selected_counts)
        current_metrics = compute_metrics(global_counts, cfg)
        all_rve_dfs.append(selected_df)
        accepted_details.append(dict(selected_detail))
        accepted_pn_vectors.append(pn_distribution_vector(selected_counts["PN"]))

        # Update sample weights globally and refresh previously saved RVE files as well.
        all_rve_dfs = update_sample_weights(all_rve_dfs, global_counts, cfg)
        selected_df = all_rve_dfs[-1]

        # Save outputs
        save_rve_folder(selected_df, k, out_root, current_metrics, selected_detail)
        all_candidate_details.extend(round_details)

        hist_row = {
            "K": k,
            "Selected_Family": selected_detail.get("family", "UNKNOWN"),
            "Selected_Score": float(selected_detail.get("score", 0.0)),
            "C_PN": current_metrics["C_PN"],
            "C_PO": current_metrics["C_PO"],
            "R_ge_2": current_metrics.get("R_ge_2", 0.0),
            "R_ge_3": current_metrics.get("R_ge_3", 0.0),
            "R_ge_4": current_metrics.get("R_ge_4", 0.0),
            "R_ge_5": current_metrics.get("R_ge_5", 0.0),
            "R_ge_6": current_metrics.get("R_ge_6", 0.0),
            "R_3": current_metrics.get("R_ge_3", 0.0),
            "Mean_Group_Count": current_metrics.get("Mean_Group_Count", 0.0),
            "N_undercovered": current_metrics["N_undercovered"],
            "N_effectively_covered": current_metrics["N_effectively_covered"],
            "Zero_PN_states": current_metrics["Zero_PN_states"],
            "W95": current_metrics["W95"],
            "W95_capped": current_metrics["W95_capped"],
            "Wmax_capped": current_metrics["Wmax_capped"],
            "W95_raw": current_metrics["W95_raw"],
            "Wmax_raw": current_metrics["Wmax_raw"],
            "Cap_hit_states": current_metrics["Cap_hit_states"],
            "Cap_hit_ratio": current_metrics["Cap_hit_ratio"],
            "CV_PN": current_metrics["CV_PN"],
            "CV_PN_BCC": current_metrics.get("CV_PN_BCC", np.nan),
            "CV_PN_HCP": current_metrics.get("CV_PN_HCP", np.nan),
            "CV_PN_PHASE_MEAN": current_metrics.get("CV_PN_PHASE_MEAN", np.nan),
            "PN_total_deficit": current_metrics.get("PN_total_deficit", 0),
        }
        if history:
            prev = history[-1]
            hist_row["dC_PN"] = hist_row["C_PN"] - prev["C_PN"]
            hist_row["dC_PO"] = hist_row["C_PO"] - prev["C_PO"]
            hist_row["dR_ge_4"] = hist_row["R_ge_4"] - prev["R_ge_4"]
            hist_row["dN_undercovered_reduction"] = int(prev["N_undercovered"] - hist_row["N_undercovered"])
        else:
            hist_row["dC_PN"] = np.nan
            hist_row["dC_PO"] = np.nan
            hist_row["dR_ge_4"] = np.nan
            hist_row["dN_undercovered_reduction"] = np.nan
        history.append(hist_row)

        # Refresh all RVE folders with updated Sample_Weight, while preserving
        # each RVE's original candidate detail in rve_info.json.
        for idx, d in enumerate(all_rve_dfs, start=1):
            detail_to_save = dict(accepted_details[idx - 1])
            detail_to_save["weight_refresh_after_K"] = k
            save_rve_folder(d, idx, out_root, current_metrics, detail_to_save)

        save_global_outputs(out_root, all_rve_dfs, global_counts, history, all_candidate_details, cfg)
        plot_dashboard(history, out_root, cfg)
        print_round_summary(k, selected_detail, current_metrics, history, cfg)

        flags = stop_criteria_check(history, cfg)

        full_existence = int(current_metrics.get("Zero_PN_states", 0)) == 0

        if auto_mode or cfg.AUTO_STOP_ENABLED:
            if (
                flags.get("ALL", False)
                and k >= 2
                and (
                    full_existence
                    or not cfg.REQUIRE_FULL_PN_EXISTENCE_BEFORE_STOP
                )
            ):
                print("Auto-stop: all stop criteria are met and full Phase-Ndiff existence is satisfied.")
                break
            continue

        ans = ask_continue(cfg, flags.get("ALL", False))

        if ans == "n":
            if (
                cfg.REQUIRE_FULL_PN_EXISTENCE_BEFORE_STOP
                and not full_existence
            ):
                print(
                    "Cannot stop yet: %d Phase-Ndiff state(s) are still absent. "
                    "The next RVE will prioritize them."
                    % int(current_metrics.get("Zero_PN_states", 0))
                )
                continue

            print("Stopped by user.")
            break
        if ans == "a":
            print("Switching to auto mode. The script will continue until stop criteria or MAX_RVE_COUNT.")
            auto_mode = True

    final_zero_states = int(current_metrics.get("Zero_PN_states", 0))
    if cfg.REQUIRE_FULL_PN_EXISTENCE_BEFORE_STOP and final_zero_states > 0:
        raise RuntimeError(
            "MAX_RVE_COUNT reached but %d Phase-Ndiff state(s) are still absent. "
            "Increase MAX_RVE_COUNT or candidate count." % final_zero_states
        )

    print("\nAdaptive basis-RVE construction finished.")
    print("Output root:", str(out_root))
    print("Use RVE_XXX/inp_injection_table.csv or RVE_all_master_current.csv for later INP injection.")


