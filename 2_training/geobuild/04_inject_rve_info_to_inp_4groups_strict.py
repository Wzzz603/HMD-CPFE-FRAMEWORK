def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def read_text_lines(path: Path) -> List[str]:
    with open(path, "r", errors="ignore") as f:
        return f.readlines()


def write_text_lines(path: Path, lines: Sequence[str]) -> None:
    ensure_dir(path.parent)
    with open(path, "w", newline="") as f:
        f.writelines(lines)


def split_eol_text(line: str) -> Tuple[str, str]:
    if line.endswith("\r\n"):
        return line[:-2], "\r\n"
    if line.endswith("\n"):
        return line[:-1], "\n"
    if line.endswith("\r"):
        return line[:-1], "\r"
    return line, ""


def is_keyword(line: str) -> bool:
    return line.lstrip().startswith("*")


def keyword_lower(line: str) -> str:
    return line.strip().lower()


def compact_lower(line: str) -> str:
    content, _ = split_eol_text(line)
    return content.lower().replace(" ", "").replace("\t", "")


def parse_keyword_options(line: str) -> Dict[str, str]:
    opts: Dict[str, str] = {}
    parts = line.strip().split(",")
    for token in parts[1:]:
        token = token.strip()
        if "=" in token:
            k, v = token.split("=", 1)
            opts[k.strip().lower()] = v.strip()
    return opts


def format_float(x, fmt: str) -> str:
    try:
        return fmt.format(float(x))
    except Exception:
        return str(x)


def format_abaqus_real(x, fmt: str) -> str:
    """Format every UMAT property as an Abaqus real number.

    Integer-valued properties are intentionally written with a trailing dot
    (for example ``7134.``), matching the style of the original INP.
    """
    value = float(x)
    if not math.isfinite(value):
        raise ValueError("Non-finite material property: %r" % x)
    nearest = round(value)
    if abs(value - nearest) <= 1.0e-12 * max(1.0, abs(value)):
        return "%d." % int(nearest)
    text = fmt.format(value)
    # Keep a real-looking token when a custom format returns an integer string.
    if not any(ch in text.lower() for ch in (".", "e")):
        text += "."
    return text


def chunked(seq: Sequence, n: int) -> Iterable[Sequence]:
    for i in range(0, len(seq), n):
        yield seq[i:i + n]


def format_data_lines(values: Sequence, max_per_line: int, float_fmt: str) -> List[str]:
    """Format Abaqus *User Material data.

    Abaqus accepts at most eight constants on one data line. Therefore the
    required nine properties are deliberately written as 8 + 1 lines. This is
    not an extra material block; the second line continues the same
    ``*User Material, constants=9`` definition.
    """
    if int(max_per_line) <= 0 or int(max_per_line) > 8:
        raise ValueError("MAX_VALUES_PER_LINE must be in 1..8 for Abaqus material data.")
    str_values = [format_abaqus_real(v, float_fmt) for v in values]
    return [" " + ", ".join(part) + "\n" for part in chunked(str_values, int(max_per_line))]

def normalize_rve_name(rve_id: int) -> str:
    return "RVE_%03d" % int(rve_id)


def case_key(case: CaseItem) -> str:
    return "%s_%s_%s" % (case.case_id, case.rate_tag, case.temp_tag)


