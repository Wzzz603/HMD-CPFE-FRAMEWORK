def validate_active_case_configuration(
    load_group: str,
    cases: Sequence[CaseItem],
) -> None:
    """Validate the four load-group tables before any INP is touched."""
    if len(cases) != 9:
        raise ValueError("%s must contain exactly 9 cases; found %d." % (load_group, len(cases)))

    filenames = [c.filename for c in cases]
    if len(set(filenames)) != len(filenames):
        raise ValueError("Duplicated case filenames in %s." % load_group)

    expected_temperatures = {
        "20": 293.15,
        "500": 773.15,
        "800": 1073.15,
    }
    monotonic = load_group in ("01_Tension", "02_Compression")
    expected_abs_h33 = 0.108 if monotonic else 0.054
    expected_sign = 1.0 if load_group in ("01_Tension", "03_TensionReversal") else -1.0

    for case in cases:
        points = tuple(
            (
                float(str(t).replace("D", "E").replace("d", "e")),
                float(str(a).replace("D", "E").replace("d", "e")),
            )
            for t, a in case.amplitude_points
        )
        if len(points) < 2 or any(points[i][0] <= points[i - 1][0] for i in range(1, len(points))):
            raise ValueError("Amplitude times must be strictly increasing for %s." % case.filename)
        if not np.allclose(points[0], (0.0, 0.0), rtol=0.0, atol=1.0e-14):
            raise ValueError("%s must start from amplitude point (0, 0)." % case.filename)

        static_values = [
            float(x.strip().replace("D", "E").replace("d", "e"))
            for x in case.static_line.split(",")
            if x.strip()
        ]
        if len(static_values) != 4:
            raise ValueError("%s must have four *Static values." % case.filename)

        total_time = points[-1][0]
        output_interval = float(case.output_interval)
        if abs(static_values[1] - total_time) > 1.0e-12:
            raise ValueError(
                "%s: *Static total time=%g differs from amplitude end time=%g."
                % (case.filename, static_values[1], total_time)
            )
        if (
            abs(static_values[0] - output_interval) > 1.0e-14
            or abs(static_values[3] - output_interval) > 1.0e-14
        ):
            raise ValueError(
                "%s: initial/max *Static increments must equal output_interval."
                % case.filename
            )
        n_intervals = total_time / output_interval
        if abs(n_intervals - 180.0) > 1.0e-9:
            raise ValueError(
                "%s: expected 180 standard intervals, obtained %.12g."
                % (case.filename, n_intervals)
            )

        if monotonic:
            expected_points = ((0.0, 0.0), (total_time, 1.0))
        else:
            expected_points = ((0.0, 0.0), (0.5 * total_time, 1.0), (total_time, 0.0))
        if not np.allclose(
            np.asarray(points),
            np.asarray(expected_points),
            rtol=0.0,
            atol=1.0e-12,
        ):
            raise ValueError(
                "%s has unexpected amplitude history: %s; expected %s."
                % (case.filename, points, expected_points)
            )

        parts = [x.strip() for x in case.boundary_line.split(",")]
        if len(parts) != 4:
            raise ValueError("Invalid boundary_line for %s: %s" % (case.filename, case.boundary_line))
        if parts[0].upper() != "PBC_REFMACRO3" or parts[1:3] != ["3", "3"]:
            raise ValueError(
                "%s must control PBC_REFMACRO3 DOF 3 for the current four groups."
                % case.filename
            )
        h33 = float(parts[3])
        if abs(abs(h33) - expected_abs_h33) > 1.0e-12 or math.copysign(1.0, h33) != expected_sign:
            raise ValueError(
                "%s has unexpected H33=%g for load group %s."
                % (case.filename, h33, load_group)
            )

        expected_temp = expected_temperatures.get(case.temp_tag)
        if expected_temp is None or abs(float(case.temperature) - expected_temp) > 1.0e-9:
            raise ValueError(
                "%s has inconsistent temperature tag/value: %s / %s."
                % (case.filename, case.temp_tag, case.temperature)
            )


validate_active_case_configuration(CFG.ACTIVE_LOAD_GROUP, CASES)


