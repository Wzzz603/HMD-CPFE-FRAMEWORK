def find_material_region(lines: Sequence[str]) -> Optional[Tuple[int, int]]:
    """Return only the material-definition region.

    It must stop before the Initial boundary conditions / predefined field /
    analysis step. This prevents material injection from deleting the PBC
    anchors or the temperature assignment.
    """
    start = None
    for i, line in enumerate(lines):
        if keyword_lower(line).startswith("*material"):
            start = i
            break
    if start is None:
        return None

    end_patterns = (
        r"^\s*\*\*\s*BOUNDARY\s+CONDITIONS\b",
        r"^\s*\*\*\s*PREDEFINED\s+FIELDS\b",
        r"^\s*\*\*\s*STEP\b",
        r"^\s*\*\*\s*INTERACTIONS?\b",
        r"^\s*\*\*\s*LOADS?\b",
        r"^\s*\*\*\s*OUTPUT\s+REQUESTS\b",
        r"^\s*\*Boundary\b",
        r"^\s*\*Initial\s+Conditions\b",
        r"^\s*\*Step\b",
        r"^\s*\*Assembly\b",
        r"^\s*\*End\s+Assembly\b",
    )
    end = len(lines)
    for j in range(start + 1, len(lines)):
        if any(re.search(p, lines[j], flags=re.IGNORECASE) for p in end_patterns):
            end = j
            break
    while end > start and lines[end - 1].strip() in ("", "**"):
        end -= 1
    return start, end


def split_material_blocks(lines: Sequence[str], material_region: Tuple[int, int]) -> List[List[str]]:
    start, end = material_region
    starts = [i for i in range(start, end) if keyword_lower(lines[i]).startswith("*material")]
    if not starts:
        return []
    bounds = starts[1:] + [end]
    return [list(lines[s:e]) for s, e in zip(starts, bounds)]


def material_keyword_signature(block: Sequence[str]) -> Tuple[str, ...]:
    signature: List[str] = []
    for line in block:
        stripped = line.strip()
        if not stripped or stripped.startswith("**"):
            continue
        if stripped.startswith("*"):
            signature.append(stripped.split(",", 1)[0].strip().lower())
    return tuple(signature)


def parse_declared_constants(keyword_line: str) -> Optional[int]:
    m = re.search(r"\bconstants\s*=\s*(\d+)", keyword_line, flags=re.IGNORECASE)
    return int(m.group(1)) if m else None


def parse_keyword_data_values(block: Sequence[str], keyword_prefix: str) -> Tuple[Optional[str], List[float]]:
    for i, line in enumerate(block):
        if keyword_lower(line).startswith(keyword_prefix.lower()):
            values: List[float] = []
            j = i + 1
            while j < len(block):
                stripped = block[j].strip()
                if stripped.startswith("*"):
                    break
                if stripped and not stripped.startswith("**"):
                    for token in stripped.split(","):
                        token = token.strip()
                        if token:
                            values.append(float(token.replace("D", "E").replace("d", "e")))
                j += 1
            return line, values
    return None, []


def validate_template_material_structure(lines: Sequence[str], cfg: Config) -> List[str]:
    region = find_material_region(lines)
    if region is None:
        raise RuntimeError("The template contains no *Material region.")
    blocks = split_material_blocks(lines, region)
    if not blocks:
        raise RuntimeError("The template material region contains no material blocks.")

    expected_signature = material_keyword_signature(blocks[0])
    required_signature = ("*material", "*depvar", "*user material")
    if expected_signature != required_signature:
        raise RuntimeError(
            "Unexpected original material keyword order. Expected %s, found %s"
            % (required_signature, expected_signature)
        )

    for idx, block in enumerate(blocks, start=1):
        sig = material_keyword_signature(block)
        if cfg.REQUIRE_UNIFORM_TEMPLATE_MATERIAL_STRUCTURE and sig != expected_signature:
            raise RuntimeError("Original material block %d has a different keyword structure: %s" % (idx, sig))

        _, depvar_values = parse_keyword_data_values(block, "*depvar")
        if len(depvar_values) != 1 or int(round(depvar_values[0])) != int(cfg.EXPECTED_DEPVAR_COUNT):
            raise RuntimeError(
                "Original material block %d does not define *Depvar = %d"
                % (idx, int(cfg.EXPECTED_DEPVAR_COUNT))
            )

        user_line, user_values = parse_keyword_data_values(block, "*user material")
        declared = parse_declared_constants(user_line or "")
        if declared is None or declared != len(user_values):
            raise RuntimeError(
                "Original material block %d has inconsistent *User Material constants: declared=%s, data=%d"
                % (idx, declared, len(user_values))
            )
    return blocks[0]


def make_user_material_constants(row: pd.Series, cfg: Config) -> List[float]:
    # PROPS(1:9): phi1, Phi, phi2, feature/element id, phase id,
    # readfromprops flag, N_total, N_diff, Sample_Weight.
    return [
        float(row["phi1"]),
        float(row["Phi"]),
        float(row["phi2"]),
        float(int(row["Element_ID"])),
        float(int(row["Phase"])),
        float(cfg.RESERVED_CONSTANT_6),
        float(int(row.get("N_total", cfg.N_TOTAL_NEIGHBORS))),
        float(int(row["N_diff"])),
        float(row["Sample_Weight"]),
    ]


def material_name_for_element(eid: int, cfg: Config) -> str:
    return "%s%d" % (cfg.MATERIAL_PREFIX, int(eid))


def grain_set_name_for_element(eid: int, cfg: Config) -> str:
    return "%s%d" % (cfg.GRAIN_SET_PREFIX, int(eid))


def transform_material_prototype(
    prototype_lines: Sequence[str],
    material_name: str,
    constants: Sequence[float],
    cfg: Config,
) -> List[str]:
    """Clone the original material block and replace only name/user constants."""
    out: List[str] = []
    i = 0
    user_written = False
    while i < len(prototype_lines):
        line = prototype_lines[i]
        low = keyword_lower(line)
        if low.startswith("*material"):
            out.append("*Material, name=%s\n" % material_name)
            i += 1
            continue
        if low.startswith("*user material"):
            out.append("*User Material, constants=%d\n" % int(cfg.USER_MATERIAL_CONSTANTS))
            out.extend(format_data_lines(constants, cfg.MAX_VALUES_PER_LINE, cfg.FLOAT_FORMAT))
            user_written = True
            i += 1
            # Delete only the old *User Material data lines. Preserve the next
            # keyword and every other material subkeyword exactly.
            while i < len(prototype_lines) and not is_keyword(prototype_lines[i]):
                i += 1
            continue
        out.append(line)
        i += 1

    if not user_written:
        raise RuntimeError("The original material prototype has no *User Material keyword.")
    return out


def make_minimal_material_block(material_name: str, constants: Sequence[float], cfg: Config) -> List[str]:
    if not cfg.FALLBACK_MINIMAL_MATERIAL:
        raise RuntimeError("Minimal material fallback is disabled; a valid original prototype is required.")
    lines = [
        "*Material, name=%s\n" % material_name,
        "*Depvar\n",
        "    %d,\n" % int(cfg.EXPECTED_DEPVAR_COUNT),
        "*User Material, constants=%d\n" % int(cfg.USER_MATERIAL_CONSTANTS),
    ]
    lines.extend(format_data_lines(constants, cfg.MAX_VALUES_PER_LINE, cfg.FLOAT_FORMAT))
    return lines


def generate_material_blocks(df: pd.DataFrame, template_lines: Sequence[str], cfg: Config) -> List[str]:
    prototype: Optional[List[str]] = None
    if cfg.USE_TEMPLATE_MATERIAL_PROTOTYPE:
        prototype = validate_template_material_structure(template_lines, cfg)
    if prototype is None and not cfg.FALLBACK_MINIMAL_MATERIAL:
        raise RuntimeError("No valid material prototype found and FALLBACK_MINIMAL_MATERIAL=False.")

    out: List[str] = []
    out.append("** ----------------------------------------------------------------\n")
    out.append("** Element-wise materials generated by 04_inject_rve_info_to_inp_with_case_bc_control_strict.py\n")
    out.append("** PROPS: phi1, Phi, phi2, Element_ID, Phase, 0, N_total, N_diff, Sample_Weight\n")
    out.append("** Nine constants are written on 8 + 1 Abaqus data lines.\n")
    out.append("** ----------------------------------------------------------------\n")

    for _, row in df.iterrows():
        eid = int(row["Element_ID"])
        mat_name = material_name_for_element(eid, cfg)
        constants = make_user_material_constants(row, cfg)
        if prototype is not None:
            out.extend(transform_material_prototype(prototype, mat_name, constants, cfg))
        else:
            out.extend(make_minimal_material_block(mat_name, constants, cfg))
    return out


