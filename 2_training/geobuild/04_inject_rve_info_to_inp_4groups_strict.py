def elset_lines(name: str, ids: Sequence[int], cfg: Config) -> List[str]:
    lines = ["*Elset, elset=%s\n" % name]
    ids_sorted = [int(x) for x in ids]
    for part in chunked(ids_sorted, cfg.ELSET_IDS_PER_LINE):
        lines.append(", ".join(str(int(v)) for v in part) + "\n")
    return lines


def generate_part_microstructure_block(df: pd.DataFrame, cfg: Config) -> List[str]:
    """Generate the Part block in the same high-level order as the original INP.

    Order: GRAIN elsets -> PHASE elsets -> Section assignments.
    """
    lines: List[str] = []
    lines.append("** ----------------------------------------------------------------\n")
    lines.append("** RVE microstructure block generated by 04_inject_rve_info_to_inp_with_case_bc_control_strict.py\n")
    lines.append("** ----------------------------------------------------------------\n")

    lines.append("** Element-wise grain elsets\n")
    for eid in df["Element_ID"].astype(int).tolist():
        lines.extend(elset_lines(grain_set_name_for_element(eid, cfg), [eid], cfg))

    lines.append("** Phase elsets\n")
    for phase in sorted(df["Phase"].unique()):
        ids = df.loc[df["Phase"] == phase, "Element_ID"].astype(int).tolist()
        lines.extend(elset_lines("%s%d" % (cfg.PHASE_SET_PREFIX, int(phase)), ids, cfg))

    lines.append("** Section assignments\n")
    for eid in df["Element_ID"].astype(int).tolist():
        lines.append("** Section: Section-%d-GRAIN-%d\n" % (eid, eid))
        lines.append("*Solid Section, elset=%s, material=%s\n" % (
            grain_set_name_for_element(eid, cfg),
            material_name_for_element(eid, cfg),
        ))
        lines.append(",\n")
    return lines


