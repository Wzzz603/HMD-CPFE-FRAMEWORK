def detect_rve_ids(rve_root: Path) -> List[int]:
    ids = []
    for p in rve_root.iterdir():
        if not p.is_dir():
            continue
        m = re.match(r"RVE_(\d+)$", p.name, re.IGNORECASE)
        if m and (p / "inp_injection_table.csv").exists():
            ids.append(int(m.group(1)))
    return sorted(ids)


def normalize_rve_ids(rve_ids) -> List[int]:
    if isinstance(rve_ids, int):
        return [int(rve_ids)]
    if isinstance(rve_ids, str):
        return [int(x.strip()) for x in rve_ids.split(",") if x.strip()]
    return [int(x) for x in rve_ids]


def load_injection_table(path: Path, cfg: Config) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError("RVE injection table not found: %s" % str(path))

    df = pd.read_csv(path)
    required = {"Element_ID", "Phase", "N_diff", "Orientation_ID", "phi1", "Phi", "phi2", "Sample_Weight"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError("Injection table missing required columns %s in %s" % (sorted(missing), str(path)))

    if "N_total" not in df.columns:
        df["N_total"] = cfg.N_TOTAL_NEIGHBORS

    df = df.copy()
    for col in ["Element_ID", "Phase", "N_diff", "N_total"]:
        df[col] = pd.to_numeric(df[col], errors="raise").astype(int)
    df["Orientation_ID"] = df["Orientation_ID"].astype(str)
    for col in ["phi1", "Phi", "phi2", "Sample_Weight"]:
        df[col] = pd.to_numeric(df[col], errors="raise")

    if df["Element_ID"].duplicated().any():
        dup = df.loc[df["Element_ID"].duplicated(), "Element_ID"].head(10).tolist()
        raise ValueError("Duplicated Element_ID in %s, examples: %s" % (str(path), dup))
    if (df["Element_ID"] <= 0).any():
        raise ValueError("Element_ID must be positive in %s" % str(path))

    allowed_phases = {int(cfg.BCC_PHASE_ID), int(cfg.HCP_PHASE_ID)}
    actual_phases = set(df["Phase"].astype(int).unique().tolist())
    if not actual_phases.issubset(allowed_phases):
        raise ValueError("Unexpected Phase values %s; allowed=%s" % (sorted(actual_phases), sorted(allowed_phases)))

    if (df["N_total"] < 0).any() or (df["N_total"] > int(cfg.N_TOTAL_NEIGHBORS)).any():
        raise ValueError("N_total must be within 0..%d" % int(cfg.N_TOTAL_NEIGHBORS))
    if (df["N_diff"] < 0).any() or (df["N_diff"] > df["N_total"]).any():
        raise ValueError("N_diff must satisfy 0 <= N_diff <= N_total")
    if (df["Sample_Weight"] <= 0.0).any():
        raise ValueError("Sample_Weight must be positive")

    numeric = df[["phi1", "Phi", "phi2", "Sample_Weight"]].to_numpy(dtype=float)
    if not np.isfinite(numeric).all():
        raise ValueError("Non-finite Euler angle or Sample_Weight in %s" % str(path))

    return df.sort_values("Element_ID").reset_index(drop=True)


