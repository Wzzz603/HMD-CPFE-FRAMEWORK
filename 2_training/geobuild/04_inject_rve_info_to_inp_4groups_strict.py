"""
04_inject_rve_info_to_inp_with_4loadgroups_strict.py

Purpose
-------
Step-04 for the CPFE basis-RVE workflow.

This script does TWO things in one pass:

1) Case control / working-condition update
   It updates each INP template according to the CASES table:
       - temperature in *Initial Conditions, type=TEMPERATURE
       - complete AMP-1 time-amplitude history
       - *Static increment line
       - *Output field/history time interval
       - target boundary data line under *Boundary, amplitude=AMP-1

2) RVE injection
   It injects each RVE_K/inp_injection_table.csv generated by Step-03 into
   every case INP and writes:
       OUTPUT_ROOT/RVE_001/01_001_20.inp
       OUTPUT_ROOT/RVE_001/02_001_500.inp
       ...

What this script changes
------------------------
- Case settings: temperature, amplitude end time, static line, output interval,
  target boundary condition data line.
- RVE microstructure blocks: GRAIN-* elsets, PHASE-* elsets, *Solid Section,
  *Material/*User Material constants.

What this script preserves
--------------------------
- Nodes and elements.
- Assembly / instance / PBC equations.
- Other boundary conditions and output requests, except the time interval lines
  configured by CASES.

Recommended usage
-----------------
Run with normal Python, not Abaqus Python:
    python 04_inject_rve_info_to_inp_with_4loadgroups_strict.py

Notes
-----
- CASES uses the same idea as your previous 01_001_20 -> 9-case generator.
- static_line controls Abaqus internal increment size.
- output_interval controls how often Abaqus writes field/history output.
- boundary_line controls the exact data line under *Boundary, amplitude=AMP-1,
  for example: PBC_REFMACRO3, 3, 3, 0.162.
  These controls can be different. For example, use smaller static increments
  for convergence while keeping output_interval unchanged.
"""
