def replace_temperature(lines: List[str], temp_value: str) -> Tuple[List[str], int]:
    temp_s = str(temp_value)
    changed = 0
    i = 0
    pattern = re.compile(r"^(.*?TEMP_NODESET\s*,\s*)" + NUM + r"(.*)$", flags=re.IGNORECASE)

    while i < len(lines):
        cl = compact_lower(lines[i])
        if cl.startswith("*initialconditions") and "type=temperature" in cl:
            j = i + 1
            while j < len(lines):
                content, eol = split_eol_text(lines[j])
                stripped = content.strip()
                if stripped.startswith("**") or stripped == "":
                    j += 1
                    continue
                if stripped.startswith("*"):
                    break
                if "TEMP_NODESET" in content.upper():
                    new_content, n = pattern.subn(lambda m: m.group(1) + temp_s + m.group(2), content, count=1)
                    if n != 1:
                        raise RuntimeError("Found TEMP_NODESET line but failed to replace temperature.")
                    lines[j] = new_content + eol
                    changed += 1
                    break
                j += 1
        i += 1

    if changed == 0:
        raise RuntimeError("No temperature definition found after *Initial Conditions, type=TEMPERATURE.")
    return lines, changed


def _amp_token(value: str) -> str:
    """Abaqus-friendly amplitude token while retaining configured precision."""
    raw = str(value).strip()
    x = float(raw.replace("D", "E").replace("d", "e"))
    if abs(x - round(x)) <= 1.0e-14:
        return "%d." % int(round(x))
    return raw


def _normalized_amplitude_points(
    amplitude_points: Sequence[Tuple[str, str]]
) -> Tuple[Tuple[float, float], ...]:
    if len(amplitude_points) < 2:
        raise ValueError("Amplitude must contain at least two (time, value) points.")
    pts: List[Tuple[float, float]] = []
    for t_raw, a_raw in amplitude_points:
        t = float(str(t_raw).replace("D", "E").replace("d", "e"))
        a = float(str(a_raw).replace("D", "E").replace("d", "e"))
        if not math.isfinite(t) or not math.isfinite(a):
            raise ValueError("Non-finite amplitude point: %r" % ((t_raw, a_raw),))
        pts.append((t, a))
    for i in range(1, len(pts)):
        if not pts[i][0] > pts[i - 1][0]:
            raise ValueError("Amplitude times must be strictly increasing: %s" % (pts,))
    return tuple(pts)


def replace_amplitude(
    lines: List[str],
    amplitude_points: Sequence[Tuple[str, str]],
    cfg: Config,
) -> Tuple[List[str], int]:
    """Replace the complete AMP-1 history.

    For the standard monotonic history ``(0,0) -> (t_end,1)``, the function
    intentionally follows the legacy 04 behavior: it only replaces the third
    number on the existing four-value data line. This keeps monotonic tension
    and compression outputs directly comparable with the previous strict 04.

    For reversal histories, all amplitude data values are replaced with the
    configured multi-point history.
    """
    desired = _normalized_amplitude_points(amplitude_points)
    target = "name=" + str(cfg.BOUNDARY_AMPLITUDE_NAME).lower().replace(" ", "")

    keyword_index: Optional[int] = None
    for i, line in enumerate(lines):
        cl = compact_lower(line)
        if cl.startswith("*amplitude") and target in cl:
            keyword_index = i
            break
    if keyword_index is None:
        raise RuntimeError(
            "No *Amplitude, name=%s keyword found." % cfg.BOUNDARY_AMPLITUDE_NAME
        )

    block_end = len(lines)
    for j in range(keyword_index + 1, len(lines)):
        if lines[j].lstrip().startswith("*") and not lines[j].lstrip().startswith("**"):
            block_end = j
            break

    data_indices: List[int] = []
    existing_values: List[float] = []
    for j in range(keyword_index + 1, block_end):
        stripped = lines[j].strip()
        if not stripped or stripped.startswith("**"):
            continue
        data_indices.append(j)
        for token in stripped.split(","):
            token = token.strip()
            if token:
                existing_values.append(float(token.replace("D", "E").replace("d", "e")))

    if not data_indices:
        raise RuntimeError(
            "No amplitude data found after *Amplitude, name=%s."
            % cfg.BOUNDARY_AMPLITUDE_NAME
        )

    # Preserve the old output text exactly for the two monotonic groups.
    legacy_monotonic = (
        len(desired) == 2
        and np.allclose(np.asarray(desired[0]), np.asarray((0.0, 0.0)), rtol=0.0, atol=1.0e-14)
        and abs(desired[1][1] - 1.0) <= 1.0e-14
        and len(data_indices) == 1
        and len(existing_values) == 4
    )
    if legacy_monotonic:
        j = data_indices[0]
        content, eol = split_eol_text(lines[j])
        parts = content.split(",")
        if len(parts) < 4:
            raise RuntimeError("Malformed four-value amplitude data line: %s" % content)
        parts[2] = "             " + str(amplitude_points[-1][0])
        lines[j] = ",".join(parts) + eol
        return lines, 1

    first_data = data_indices[0]
    last_data = data_indices[-1] + 1
    _, eol = split_eol_text(lines[first_data])
    if not eol:
        _, eol = split_eol_text(lines[keyword_index])
    if not eol:
        eol = "\n"

    tokens: List[str] = []
    for t_raw, a_raw in amplitude_points:
        tokens.extend([_amp_token(t_raw), _amp_token(a_raw)])

    # Abaqus accepts up to eight values per data line. Current reversal paths
    # contain six values and are therefore written on one line.
    new_data_lines: List[str] = []
    for part in chunked(tokens, 8):
        new_data_lines.append(" " + ", ".join(part) + eol)

    lines[first_data:last_data] = new_data_lines
    return lines, 1


def replace_static(lines: List[str], static_line: str) -> Tuple[List[str], int]:
    changed = 0
    for i in range(len(lines) - 1):
        if keyword_lower(lines[i]).startswith("*static"):
            j = i + 1
            while j < len(lines):
                content, eol = split_eol_text(lines[j])
                stripped = content.strip()
                if stripped.startswith("**") or stripped == "":
                    j += 1
                    continue
                if stripped.startswith("*"):
                    break
                lines[j] = str(static_line) + eol
                changed += 1
                break
            break

    if changed == 0:
        raise RuntimeError("No *Static data line found.")
    return lines, changed


def replace_output_intervals(lines: List[str], interval: str) -> Tuple[List[str], int]:
    """Replace every ``time interval=...`` option on *Output lines.

    The option may appear anywhere in the keyword line, for example both of
    the following are supported:

        *Output, field, time interval=0.06
        *Output, field, variable=PRESELECT, time interval=0.06

    Only *Output field/history keyword lines are touched.
    """
    interval_s = str(interval)
    changed = 0
    time_pattern = re.compile(
        r"(\btime\s+interval\s*=\s*)" + NUM,
        flags=re.IGNORECASE,
    )

    for i in range(len(lines)):
        content, eol = split_eol_text(lines[i])
        low = content.lstrip().lower()
        if not low.startswith("*output"):
            continue
        if not re.search(r"^\s*\*Output\s*,.*\b(field|history)\b", content, flags=re.IGNORECASE):
            continue
        new_content, n = time_pattern.subn(
            lambda m: m.group(1) + interval_s,
            content,
            count=1,
        )
        if n == 1:
            lines[i] = new_content + eol
            changed += 1

    if changed == 0:
        raise RuntimeError("No *Output field/history line containing time interval=... was found.")
    return lines, changed

def replace_boundary_line(lines: List[str], boundary_line: str, cfg: Config) -> Tuple[List[str], int]:
    """Replace the target PBC boundary data line under *Boundary, amplitude=AMP-1.

    Unlike the previous macro_h33-only replacement, this replaces the whole
    data line, so the reference point name, DOF range, and value can all be
    configured from CASES, for example:
        PBC_REFMACRO3, 3, 3, 0.162
        PBC_REFMACRO1, 1, 1, 0.162
        PBC_REFMACRO3, 3, 3, -0.162
    """
    new_line = str(boundary_line).strip()
    if not new_line:
        raise RuntimeError("Empty boundary_line in CASES.")

    changed = 0
    target_amp = str(cfg.BOUNDARY_AMPLITUDE_NAME).lower().replace(" ", "")
    target_name = str(cfg.BOUNDARY_TARGET_NAME).strip().upper()

    i = 0
    while i < len(lines):
        cl = compact_lower(lines[i])
        if cl.startswith("*boundary") and ("amplitude=" + target_amp) in cl:
            j = i + 1
            while j < len(lines):
                content, eol = split_eol_text(lines[j])
                stripped = content.strip()
                if stripped.startswith("**") or stripped == "":
                    j += 1
                    continue
                if stripped.startswith("*"):
                    break

                first_token = stripped.split(",", 1)[0].strip().upper()
                if first_token == target_name:
                    lines[j] = new_line + eol
                    changed += 1
                    break

                j += 1
        i += 1

    if changed == 0:
        raise RuntimeError(
            "No target boundary line found under *Boundary, amplitude=%s for target %s."
            % (cfg.BOUNDARY_AMPLITUDE_NAME, cfg.BOUNDARY_TARGET_NAME)
        )
    return lines, changed


def apply_case_control(lines: Sequence[str], case: CaseItem, cfg: Config) -> Tuple[List[str], Dict[str, int]]:
    out = list(lines)
    counts: Dict[str, int] = {}
    out, counts["temperature"] = replace_temperature(out, case.temperature)
    out, counts["amplitude"] = replace_amplitude(out, case.amplitude_points, cfg)
    out, counts["static"] = replace_static(out, case.static_line)
    out, counts["output_interval"] = replace_output_intervals(out, case.output_interval)
    out, counts["boundary_line"] = replace_boundary_line(out, case.boundary_line, cfg)
    for key in ("temperature", "amplitude", "static", "boundary_line"):
        if counts[key] != 1:
            raise RuntimeError("Case-control replacement '%s' must occur exactly once; found %d." % (key, counts[key]))
    if counts["output_interval"] <= 0:
        raise RuntimeError("No output interval was replaced.")
    return out, counts


