def collect_case_templates(cfg: Config) -> List[Dict]:
    """Return list of specs: template_path, output_name, case_item or None."""
    specs: List[Dict] = []
    inp_dir = Path(cfg.INPUT_INP_DIR)

    if cfg.ENABLE_CASE_CONTROL:
        if cfg.GENERATE_CASES_FROM_SINGLE_TEMPLATE:
            base = Path(cfg.BASE_TEMPLATE_INP)
            if not base.exists():
                raise FileNotFoundError("BASE_TEMPLATE_INP not found: %s" % str(base))
            for c in CASES:
                specs.append({"template_path": base, "output_name": c.filename, "case": c})
            return specs

        if not inp_dir.exists():
            raise FileNotFoundError("INPUT_INP_DIR does not exist: %s" % str(inp_dir))

        for c in CASES:
            p = inp_dir / c.filename
            if not p.exists():
                msg = "Case template not found: %s" % str(p)
                if cfg.REQUIRE_ALL_CASE_TEMPLATES:
                    raise FileNotFoundError(msg)
                print(">> [Warn]", msg)
                continue
            specs.append({"template_path": p, "output_name": c.filename, "case": c})
        return specs

    # No case control: preserve older behavior.
    if cfg.TEMPLATE_INP_FILES:
        files = [inp_dir / name for name in cfg.TEMPLATE_INP_FILES]
    else:
        files = sorted(inp_dir.glob("*.inp"))
    if not files:
        raise FileNotFoundError("No template INP files found in: %s" % str(inp_dir))
    missing = [str(p) for p in files if not p.exists()]
    if missing:
        raise FileNotFoundError("Template INP files not found: %s" % missing)
    for p in files:
        specs.append({"template_path": p, "output_name": p.name, "case": None})
    return specs


def case_to_summary_dict(c: Optional[CaseItem], cfg: Config) -> Dict:
    if c is None:
        return {}
    return {
        "case_id": c.case_id,
        "rate_tag": c.rate_tag,
        "temp_tag": c.temp_tag,
        "temperature": c.temperature,
        "amp_end_time": c.amp_end_time,
        "amplitude_points": json.dumps(c.amplitude_points, ensure_ascii=False),
        "static_line": c.static_line,
        "output_interval": c.output_interval,
        "boundary_line": c.boundary_line,
    }


# =============================================================================
# 9. Main
# =============================================================================

def main(cfg: Config = CFG) -> None:
    input_dir = Path(cfg.INPUT_INP_DIR)
    rve_root = Path(cfg.RVE_INFO_ROOT)
    base_out_root = Path(cfg.OUTPUT_ROOT)
    out_root = (
        base_out_root / cfg.ACTIVE_LOAD_GROUP
        if cfg.ADD_LOAD_GROUP_SUBDIR
        else base_out_root
    )

    if not rve_root.exists():
        raise FileNotFoundError("RVE_INFO_ROOT does not exist: %s" % str(rve_root))

    if cfg.CLEAR_OUTPUT_ROOT_ON_START and out_root.exists():
        shutil.rmtree(out_root)
    ensure_dir(out_root)

    if cfg.AUTO_DETECT_RVES:
        rve_ids = detect_rve_ids(rve_root)
    else:
        rve_ids = normalize_rve_ids(cfg.RVE_IDS)
    if not rve_ids:
        raise RuntimeError("No RVE IDs to process.")

    template_specs = collect_case_templates(cfg)

    print("=" * 90)
    print("04_inject_rve_info_to_inp_with_4loadgroups_strict.py")
    print("Input INP dir                 :", str(input_dir))
    print("Base template                 :", str(Path(cfg.BASE_TEMPLATE_INP)))
    print("Generate from single template :", cfg.GENERATE_CASES_FROM_SINGLE_TEMPLATE)
    print("Case control enabled          :", cfg.ENABLE_CASE_CONTROL)
    print("RVE info root                 :", str(rve_root))
    print("Output root                   :", str(out_root))
    print("Active load group             :", cfg.ACTIVE_LOAD_GROUP)
    print("RVE IDs                       :", rve_ids)
    print("Cases/templates               :", len(template_specs))
    print("Boundary target               : *Boundary amplitude=%s, node=%s" % (cfg.BOUNDARY_AMPLITUDE_NAME, cfg.BOUNDARY_TARGET_NAME))
    for spec in template_specs:
        c = spec["case"]
        if c is None:
            print("  -", spec["output_name"])
        else:
            print("  - %-15s | T=%s | AMP=%s | Static=%s | Output=%s | BC=%s" % (
                spec["output_name"], c.temperature, c.amplitude_points, c.static_line, c.output_interval, c.boundary_line
            ))
    print("=" * 90)

    summary_rows: List[Dict] = []
    case_summary_rows: List[Dict] = []

    for rve_id in rve_ids:
        rve_name = normalize_rve_name(rve_id)
        table_path = rve_root / rve_name / "inp_injection_table.csv"
        df = load_injection_table(table_path, cfg)

        rve_out = out_root / rve_name
        ensure_dir(rve_out)

        if cfg.WRITE_RVE_LOCAL_COPY_OF_INJECTION_TABLE:
            df.to_csv(rve_out / "inp_injection_table_used.csv", index=False)

        print("\nProcessing %s" % rve_name)
        print("  Injection table:", str(table_path))
        print("  Elements       :", len(df))
        print("  BCC/HCP        : %d / %d" % (
            int((df["Phase"] == cfg.BCC_PHASE_ID).sum()),
            int((df["Phase"] == cfg.HCP_PHASE_ID).sum()),
        ))

        generated_files: List[str] = []

        for spec in template_specs:
            template_path: Path = spec["template_path"]
            output_name: str = spec["output_name"]
            c: Optional[CaseItem] = spec["case"]

            lines = read_text_lines(template_path)
            case_counts: Dict[str, int] = {}
            if cfg.ENABLE_CASE_CONTROL and c is not None:
                lines, case_counts = apply_case_control(lines, c, cfg)

            out_path = rve_out / output_name
            result = inject_lines(lines, out_path, df, cfg, template_path.name, case=c)
            generated_files.append(str(out_path))

            result["load_group"] = cfg.ACTIVE_LOAD_GROUP
            result["RVE_ID"] = rve_id
            result["RVE_Name"] = rve_name
            result["template_file"] = str(template_path)
            result["output_file"] = str(out_path)
            result.update(case_to_summary_dict(c, cfg))
            for k, v in case_counts.items():
                result["case_replace_" + k] = v
            summary_rows.append(result)

            if c is not None:
                row = {"RVE_Name": rve_name, "output_file": str(out_path)}
                row.update(case_to_summary_dict(c, cfg))
                row.update({"replace_" + k: v for k, v in case_counts.items()})
                case_summary_rows.append(row)

            print("  generated:", str(out_path))

        meta = {
            "RVE_ID": rve_id,
            "RVE_Name": rve_name,
            "injection_table": str(table_path),
            "n_templates": len(template_specs),
            "n_elements": int(len(df)),
            "n_bcc": int((df["Phase"] == cfg.BCC_PHASE_ID).sum()),
            "n_hcp": int((df["Phase"] == cfg.HCP_PHASE_ID).sum()),
            "case_control_enabled": cfg.ENABLE_CASE_CONTROL,
            "boundary_target_name": cfg.BOUNDARY_TARGET_NAME,
            "generated_inp_files": generated_files,
        }
        with open(rve_out / "rve_inp_generation_info.json", "w", encoding="utf-8") as f:
            json.dump(meta, f, indent=2, ensure_ascii=False)

    if cfg.WRITE_SUMMARY_CSV:
        summary_path = out_root / "04_injection_summary.csv"
        with open(summary_path, "w", newline="", encoding="utf-8") as f:
            fieldnames = sorted(set().union(*(row.keys() for row in summary_rows))) if summary_rows else []
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(summary_rows)
        print("\nSummary CSV:", str(summary_path))

    if cfg.WRITE_CASE_CONTROL_SUMMARY and case_summary_rows:
        case_summary_path = out_root / "04_case_control_summary.csv"
        with open(case_summary_path, "w", newline="", encoding="utf-8") as f:
            fieldnames = sorted(set().union(*(row.keys() for row in case_summary_rows)))
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(case_summary_rows)
        print("Case control CSV:", str(case_summary_path))

    print("\nDone.")
    print("Generated %d INP files." % len(summary_rows))
    print("Output root:", str(out_root))
    print("=" * 90)


if __name__ == "__main__":
    main(CFG)
