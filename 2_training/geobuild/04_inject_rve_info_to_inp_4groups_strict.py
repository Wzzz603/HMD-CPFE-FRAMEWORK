def replace_part_microstructure(lines: Sequence[str], new_block: Sequence[str], cfg: Config) -> List[str]:
    start, end = find_microstructure_replace_range_in_part(lines, cfg)
    return list(lines[:start]) + list(new_block) + list(lines[end:])


def replace_materials(lines: Sequence[str], new_materials: Sequence[str], cfg: Config) -> List[str]:
    region = find_material_region(lines)
    if region is None:
        for i, line in enumerate(lines):
            if keyword_lower(line).startswith("*step"):
                return list(lines[:i]) + list(new_materials) + list(lines[i:])
        return list(lines) + list(new_materials)

    start, end = region
    return list(lines[:start]) + list(new_materials) + list(lines[end:])


def count_keyword(lines: Sequence[str], keyword: str) -> int:
    key = keyword.strip().lower()
    return sum(1 for line in lines if keyword_lower(line).startswith(key))


def find_block(lines: Sequence[str], start_keyword: str, end_keyword: str) -> List[str]:
    start = None
    for i, line in enumerate(lines):
        if keyword_lower(line).startswith(start_keyword.lower()):
            start = i
            break
    if start is None:
        raise RuntimeError("Block start not found: %s" % start_keyword)
    for j in range(start + 1, len(lines)):
        if keyword_lower(lines[j]).startswith(end_keyword.lower()):
            return list(lines[start:j + 1])
    raise RuntimeError("Block end not found: %s" % end_keyword)


def output_interval_values(lines: Sequence[str]) -> List[float]:
    values: List[float] = []
    pattern = re.compile(r"\btime\s+interval\s*=\s*(" + NUM + r")", flags=re.IGNORECASE)
    for line in lines:
        content, _ = split_eol_text(line)
        if not re.search(r"^\s*\*Output\s*,.*\b(field|history)\b", content, flags=re.IGNORECASE):
            continue
        m = pattern.search(content)
        if m:
            values.append(float(m.group(1).replace("D", "E").replace("d", "e")))
    return values


def configured_temperature_value(lines: Sequence[str]) -> Optional[float]:
    pattern = re.compile(r"^\s*TEMP_NODESET\s*,\s*(" + NUM + r")", flags=re.IGNORECASE)
    inside = False
    for line in lines:
        cl = compact_lower(line)
        if cl.startswith("*initialconditions") and "type=temperature" in cl:
            inside = True
            continue
        if inside:
            stripped = line.strip()
            if stripped.startswith("**") or stripped == "":
                continue
            if stripped.startswith("*"):
                break
            m = pattern.search(line)
            if m:
                return float(m.group(1).replace("D", "E").replace("d", "e"))
    return None


def target_boundary_data_lines(lines: Sequence[str], cfg: Config) -> List[str]:
    found: List[str] = []
    target_amp = str(cfg.BOUNDARY_AMPLITUDE_NAME).lower().replace(" ", "")
    target_name = str(cfg.BOUNDARY_TARGET_NAME).strip().upper()
    i = 0
    while i < len(lines):
        cl = compact_lower(lines[i])
        if cl.startswith("*boundary") and ("amplitude=" + target_amp) in cl:
            j = i + 1
            while j < len(lines):
                stripped = lines[j].strip()
                if stripped.startswith("**") or stripped == "":
                    j += 1
                    continue
                if stripped.startswith("*"):
                    break
                if stripped.split(",", 1)[0].strip().upper() == target_name:
                    found.append(stripped)
                j += 1
        i += 1
    return found


def amplitude_point_values(
    lines: Sequence[str], amplitude_name: str
) -> Optional[List[Tuple[float, float]]]:
    target = str(amplitude_name).lower().replace(" ", "")
    for i, line in enumerate(lines):
        cl = compact_lower(line)
        if not (cl.startswith("*amplitude") and ("name=" + target) in cl):
            continue

        values: List[float] = []
        j = i + 1
        while j < len(lines):
            stripped = lines[j].strip()
            if stripped.startswith("*") and not stripped.startswith("**"):
                break
            if stripped and not stripped.startswith("**"):
                for token in stripped.split(","):
                    token = token.strip()
                    if token:
                        values.append(float(token.replace("D", "E").replace("d", "e")))
            j += 1

        if len(values) < 4 or len(values) % 2 != 0:
            return None
        return [(values[k], values[k + 1]) for k in range(0, len(values), 2)]
    return None


def amplitude_end_time_value(lines: Sequence[str], amplitude_name: str) -> Optional[float]:
    points = amplitude_point_values(lines, amplitude_name)
    return None if not points else float(points[-1][0])


def static_data_values(lines: Sequence[str]) -> Optional[List[float]]:
    for i, line in enumerate(lines):
        if keyword_lower(line).startswith("*static"):
            j = i + 1
            while j < len(lines):
                stripped = lines[j].strip()
                if not stripped or stripped.startswith("**"):
                    j += 1
                    continue
                if stripped.startswith("*"):
                    return None
                return [float(x.strip().replace("D", "E").replace("d", "e"))
                        for x in stripped.split(",") if x.strip()]
    return None


def parse_named_elsets_in_first_part(lines: Sequence[str]) -> Dict[str, List[int]]:
    part_start, end_part = find_first_part_range(lines)
    result: Dict[str, List[int]] = {}
    i = part_start + 1
    while i < end_part:
        line = lines[i]
        if re.match(r"^\s*\*Elset\b", line, flags=re.IGNORECASE):
            opts = parse_keyword_options(line)
            name = opts.get("elset")
            generate = "generate" in line.lower()
            vals: List[int] = []
            j = i + 1
            while j < end_part and not is_keyword(lines[j]):
                stripped = lines[j].strip()
                if stripped and not stripped.startswith("**"):
                    vals.extend(int(float(x.strip())) for x in stripped.split(",") if x.strip())
                j += 1
            if name:
                if generate and len(vals) >= 3:
                    expanded: List[int] = []
                    for k in range(0, len(vals), 3):
                        a, b, inc = vals[k:k+3]
                        expanded.extend(range(a, b + (1 if inc > 0 else -1), inc))
                    vals = expanded
                result[name.upper()] = vals
            i = j
            continue
        i += 1
    return result


def parse_solid_section_map(lines: Sequence[str]) -> Dict[str, str]:
    result: Dict[str, str] = {}
    for line in lines:
        if re.match(r"^\s*\*Solid\s+Section\b", line, flags=re.IGNORECASE):
            opts = parse_keyword_options(line)
            elset = opts.get("elset")
            material = opts.get("material")
            if elset and material:
                result[elset.upper()] = material.upper()
    return result


def validate_generated_materials_and_sections(
    output_lines: Sequence[str], df: pd.DataFrame, cfg: Config
) -> List[str]:
    errors: List[str] = []
    region = find_material_region(output_lines)
    if region is None:
        return ["Generated material region is missing."]
    blocks = split_material_blocks(output_lines, region)
    expected_rows = {int(r["Element_ID"]): r for _, r in df.iterrows()}
    if len(blocks) != len(expected_rows):
        errors.append("Generated material block count mismatch: expected=%d, found=%d" % (len(expected_rows), len(blocks)))
        return errors

    seen: set[int] = set()
    name_re = re.compile(r"^\s*\*Material\s*,.*\bname\s*=\s*" + re.escape(cfg.MATERIAL_PREFIX) + r"(\d+)\s*$", re.I)
    for block_index, block in enumerate(blocks, start=1):
        m = name_re.match(block[0].strip())
        if not m:
            errors.append("Material block %d has unexpected name line: %s" % (block_index, block[0].strip()))
            continue
        eid = int(m.group(1))
        if eid in seen:
            errors.append("Duplicated generated material for Element_ID=%d" % eid)
            continue
        seen.add(eid)
        if eid not in expected_rows:
            errors.append("Generated material refers to unknown Element_ID=%d" % eid)
            continue

        sig = material_keyword_signature(block)
        if sig != ("*material", "*depvar", "*user material"):
            errors.append("Material %d keyword order is %s" % (eid, sig))

        _, depvar_values = parse_keyword_data_values(block, "*depvar")
        if len(depvar_values) != 1 or int(round(depvar_values[0])) != int(cfg.EXPECTED_DEPVAR_COUNT):
            errors.append("Material %d has invalid *Depvar data: %s" % (eid, depvar_values))

        user_line, values = parse_keyword_data_values(block, "*user material")
        declared = parse_declared_constants(user_line or "")
        if declared != int(cfg.USER_MATERIAL_CONSTANTS):
            errors.append("Material %d declares constants=%s, expected=%d" % (eid, declared, int(cfg.USER_MATERIAL_CONSTANTS)))
            continue
        if len(values) != int(cfg.USER_MATERIAL_CONSTANTS):
            errors.append("Material %d contains %d constants, expected=%d" % (eid, len(values), int(cfg.USER_MATERIAL_CONSTANTS)))
            continue

        expected = make_user_material_constants(expected_rows[eid], cfg)
        if not np.allclose(np.asarray(values), np.asarray(expected), rtol=0.0, atol=1.0e-9):
            errors.append("Material %d constants do not match the injection table." % eid)

    missing = sorted(set(expected_rows) - seen)
    if missing:
        errors.append("Missing generated materials, first 20 Element_IDs: %s" % missing[:20])

    elsets = parse_named_elsets_in_first_part(output_lines)
    sections = parse_solid_section_map(output_lines)
    expected_ids = set(expected_rows)
    for eid in sorted(expected_ids):
        grain = grain_set_name_for_element(eid, cfg).upper()
        mat = material_name_for_element(eid, cfg).upper()
        if elsets.get(grain) != [eid]:
            errors.append("%s must contain only element %d." % (grain, eid))
            if len(errors) > 40:
                break
        if sections.get(grain) != mat:
            errors.append("Section mapping mismatch for %s: expected material=%s, found=%s" % (grain, mat, sections.get(grain)))
            if len(errors) > 40:
                break

    for phase in sorted(df["Phase"].unique()):
        name = ("%s%d" % (cfg.PHASE_SET_PREFIX, int(phase))).upper()
        expected_phase = set(df.loc[df["Phase"] == phase, "Element_ID"].astype(int).tolist())
        found_phase = set(elsets.get(name, []))
        if found_phase != expected_phase:
            errors.append("Phase elset %s does not match injection table (expected=%d, found=%d)." % (name, len(expected_phase), len(found_phase)))
    return errors


def validate_final_inp(
    template_lines: Sequence[str],
    output_lines: Sequence[str],
    df: pd.DataFrame,
    cfg: Config,
    case: Optional[CaseItem],
    output_name: str,
) -> Dict[str, object]:
    """Fail fast when anything outside the intended replacement areas changed."""
    errors: List[str] = []

    # The node/element/assembly prefix before the original Part microstructure
    # block must remain byte-for-byte identical.
    try:
        micro_start, _ = find_microstructure_replace_range_in_part(template_lines, cfg)
        if list(template_lines[:micro_start]) != list(output_lines[:micro_start]):
            errors.append("Content before the Part microstructure block changed unexpectedly.")
    except Exception as exc:
        errors.append("Part-prefix preservation check failed: %s" % exc)

    # Everything after the material region (Initial BCs, temperature field,
    # Step, loading and outputs) must remain exactly as it was after case control.
    try:
        t_region = find_material_region(template_lines)
        o_region = find_material_region(output_lines)
        if t_region is None or o_region is None:
            errors.append("Material region missing during tail-preservation check.")
        else:
            if list(template_lines[t_region[1]:]) != list(output_lines[o_region[1]:]):
                errors.append("Post-material analysis block changed unexpectedly.")
    except Exception as exc:
        errors.append("Post-material preservation check failed: %s" % exc)

    # Assembly, equations, sets and analysis skeleton must be preserved.
    if cfg.REQUIRE_ASSEMBLY_EXACTLY_PRESERVED:
        try:
            asm_before = find_block(template_lines, "*assembly", "*end assembly")
            asm_after = find_block(output_lines, "*assembly", "*end assembly")
            if asm_before != asm_after:
                errors.append("Assembly block changed, but it must be preserved exactly.")
        except Exception as exc:
            errors.append("Assembly preservation check failed: %s" % exc)

    protected_keywords = (
        "*nset",
        "*equation",
        "*boundary",
        "*initial conditions",
        "*amplitude",
        "*step",
        "*output",
    )
    for key in protected_keywords:
        before = count_keyword(template_lines, key)
        after = count_keyword(output_lines, key)
        if before != after:
            errors.append("Keyword count changed for %s: template=%d, output=%d" % (key, before, after))

    expected_n = int(len(df))
    n_mat = count_keyword(output_lines, "*material")
    n_sec = count_keyword(output_lines, "*solid section")
    if n_mat != expected_n:
        errors.append("Material count mismatch: expected=%d, output=%d" % (expected_n, n_mat))
    if n_sec != expected_n:
        errors.append("Solid Section count mismatch: expected=%d, output=%d" % (expected_n, n_sec))
    n_depvar = count_keyword(output_lines, "*depvar")
    n_user = count_keyword(output_lines, "*user material")
    if n_depvar != expected_n:
        errors.append("Depvar count mismatch: expected=%d, output=%d" % (expected_n, n_depvar))
    if n_user != expected_n:
        errors.append("User Material count mismatch: expected=%d, output=%d" % (expected_n, n_user))
    if cfg.VALIDATE_EVERY_GENERATED_MATERIAL:
        errors.extend(validate_generated_materials_and_sections(output_lines, df, cfg))

    # Confirm all configured case controls survived the later RVE injection.
    temp_value = configured_temperature_value(output_lines)
    out_intervals = output_interval_values(output_lines)
    boundary_hits = target_boundary_data_lines(output_lines, cfg)

    if case is not None:
        expected_temp = float(case.temperature)
        if temp_value is None:
            errors.append("The final INP has no TEMP_NODESET temperature assignment.")
        elif abs(temp_value - expected_temp) > 1.0e-9:
            errors.append("Temperature mismatch: expected=%g, output=%g" % (expected_temp, temp_value))

        amp_points = amplitude_point_values(output_lines, cfg.BOUNDARY_AMPLITUDE_NAME)
        expected_amp_points = [
            (float(str(t).replace("D", "E").replace("d", "e")),
             float(str(a).replace("D", "E").replace("d", "e")))
            for t, a in case.amplitude_points
        ]
        if (
            amp_points is None
            or len(amp_points) != len(expected_amp_points)
            or not np.allclose(
                np.asarray(amp_points, dtype=float),
                np.asarray(expected_amp_points, dtype=float),
                rtol=0.0,
                atol=1.0e-12,
            )
        ):
            errors.append(
                "Amplitude history mismatch: expected=%s, output=%s"
                % (expected_amp_points, amp_points)
            )

        static_values = static_data_values(output_lines)
        expected_static = [float(x.strip().replace("D", "E").replace("d", "e"))
                           for x in str(case.static_line).split(",") if x.strip()]
        if static_values is None or len(static_values) != len(expected_static) or not np.allclose(
            np.asarray(static_values), np.asarray(expected_static), rtol=0.0, atol=1.0e-14
        ):
            errors.append("*Static data mismatch: expected=%s, output=%s" % (expected_static, static_values))

        expected_interval = float(case.output_interval)
        if not out_intervals:
            errors.append("No *Output field/history time interval was found in the final INP.")
        else:
            bad = [v for v in out_intervals if abs(v - expected_interval) > 1.0e-12]
            if bad:
                errors.append(
                    "Not all output intervals were updated. expected=%g, values=%s"
                    % (expected_interval, out_intervals)
                )
            if cfg.REQUIRE_ALL_OUTPUT_INTERVALS_EQUAL and any(
                abs(v - out_intervals[0]) > 1.0e-12 for v in out_intervals[1:]
            ):
                errors.append("Output time intervals are not identical: %s" % out_intervals)

        expected_boundary = str(case.boundary_line).strip().replace(" ", "").upper()
        normalized_hits = [x.replace(" ", "").upper() for x in boundary_hits]
        if expected_boundary not in normalized_hits:
            errors.append(
                "Configured loading boundary line is missing. expected='%s', found=%s"
                % (case.boundary_line, boundary_hits)
            )

    # Phase sets must cover exactly the injected element IDs.
    phase_total = int(sum((df["Phase"] == p).sum() for p in df["Phase"].unique()))
    if phase_total != expected_n:
        errors.append("Internal phase-table count mismatch: phase_total=%d, expected=%d" % (phase_total, expected_n))

    if errors:
        raise RuntimeError(
            "Final INP validation failed for %s:\n  - %s"
            % (output_name, "\n  - ".join(errors))
        )

    return {
        "validation_status": "Passed",
        "validation_boundary_count": count_keyword(output_lines, "*boundary"),
        "validation_initial_conditions_count": count_keyword(output_lines, "*initial conditions"),
        "validation_equation_count": count_keyword(output_lines, "*equation"),
        "validation_nset_count": count_keyword(output_lines, "*nset"),
        "validation_depvar_count": count_keyword(output_lines, "*depvar"),
        "validation_user_material_count": count_keyword(output_lines, "*user material"),
        "validation_output_intervals": ";".join(format(v, ".12g") for v in out_intervals),
        "validation_temperature": temp_value,
        "validation_amplitude_end_time": amplitude_end_time_value(output_lines, cfg.BOUNDARY_AMPLITUDE_NAME),
        "validation_amplitude_points": json.dumps(
            amplitude_point_values(output_lines, cfg.BOUNDARY_AMPLITUDE_NAME),
            ensure_ascii=False,
        ),
        "validation_static_values": ";".join(format(v, ".12g") for v in (static_data_values(output_lines) or [])),
        "validation_target_boundary_hits": len(boundary_hits),
        "validation_material_prefix": cfg.MATERIAL_PREFIX,
        "validation_user_constants": cfg.USER_MATERIAL_CONSTANTS,
    }


def inject_lines(
    template_lines: Sequence[str],
    out_path: Path,
    df: pd.DataFrame,
    cfg: Config,
    template_name_for_validation: str,
    case: Optional[CaseItem] = None,
) -> Dict:
    lines = list(template_lines)
    if cfg.VALIDATE_ELEMENT_IDS:
        validate_injection_against_template(df, lines, template_name_for_validation)

    micro_block = generate_part_microstructure_block(df, cfg)
    material_blocks = generate_material_blocks(df, lines, cfg)

    lines2 = replace_part_microstructure(lines, micro_block, cfg)
    lines3 = replace_materials(lines2, material_blocks, cfg)

    validation_result: Dict[str, object] = {}
    if cfg.STRICT_FINAL_VALIDATION:
        validation_result = validate_final_inp(
            template_lines=lines,
            output_lines=lines3,
            df=df,
            cfg=cfg,
            case=case,
            output_name=out_path.name,
        )

    if out_path.exists() and not cfg.OVERWRITE_EXISTING_INP:
        raise FileExistsError("Output INP already exists and OVERWRITE_EXISTING_INP=False: %s" % str(out_path))
    write_text_lines(out_path, lines3)

    result = {
        "output": str(out_path),
        "n_elements_injected": int(len(df)),
        "n_bcc": int((df["Phase"] == cfg.BCC_PHASE_ID).sum()),
        "n_hcp": int((df["Phase"] == cfg.HCP_PHASE_ID).sum()),
        "n_materials": int(len(df)),
    }
    result.update(validation_result)
    return result


