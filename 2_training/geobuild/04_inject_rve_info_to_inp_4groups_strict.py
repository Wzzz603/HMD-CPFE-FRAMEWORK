def find_first_part_range(lines: Sequence[str]) -> Tuple[int, int]:
    start = None
    for i, line in enumerate(lines):
        if keyword_lower(line).startswith("*part"):
            start = i
            break
    if start is None:
        raise RuntimeError("No *Part block found in template INP.")
    for j in range(start + 1, len(lines)):
        if keyword_lower(lines[j]).startswith("*end part"):
            return start, j
    raise RuntimeError("No *End Part found after first *Part.")


def find_microstructure_replace_range_in_part(lines: Sequence[str], cfg: Config) -> Tuple[int, int]:
    part_start, end_part = find_first_part_range(lines)
    grain_re = re.compile(r"^\s*\*elset\s*,.*\belset\s*=\s*" + re.escape(cfg.GRAIN_SET_PREFIX), re.IGNORECASE)
    start = None
    for i in range(part_start + 1, end_part):
        if grain_re.search(lines[i]):
            start = i
            break
    if start is None:
        raise RuntimeError(
            "Could not find first '*Elset, elset=%s...' inside Part. "
            "Please check the template." % cfg.GRAIN_SET_PREFIX
        )
    return start, end_part


def parse_template_element_ids(lines: Sequence[str]) -> List[int]:
    part_start, end_part = find_first_part_range(lines)
    ids: List[int] = []
    mode = None
    reading_c3d8 = False
    for line in lines[part_start + 1:end_part]:
        stripped = line.strip()
        if not stripped or stripped.startswith("**"):
            continue
        low = stripped.lower()
        if is_keyword(stripped):
            if low.startswith("*element") and "type=c3d8" in low:
                mode = "element"
                reading_c3d8 = True
            else:
                mode = None
                reading_c3d8 = False
            continue
        if mode == "element" and reading_c3d8:
            parts = [x.strip() for x in stripped.replace("\t", " ").split(",") if x.strip()]
            if parts:
                try:
                    ids.append(int(float(parts[0])))
                except Exception:
                    pass
    return ids


def validate_injection_against_template(df: pd.DataFrame, lines: Sequence[str], template_name: str) -> None:
    elem_ids = set(parse_template_element_ids(lines))
    if not elem_ids:
        raise RuntimeError("No C3D8 elements parsed from template: %s" % template_name)
    inj_ids = set(df["Element_ID"].astype(int).tolist())
    missing_in_template = sorted(inj_ids - elem_ids)
    missing_in_injection = sorted(elem_ids - inj_ids)
    if missing_in_template or missing_in_injection:
        msg = ["Element_ID mismatch for template %s" % template_name]
        if missing_in_template:
            msg.append("  Injection has IDs not in template, first 20: %s" % missing_in_template[:20])
        if missing_in_injection:
            msg.append("  Template has IDs not in injection, first 20: %s" % missing_in_injection[:20])
        raise RuntimeError("\n".join(msg))


